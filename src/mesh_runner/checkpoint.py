"""Private, durable checkpoints. No source is changed until a scratch replay verifies.

The slim form (default) stores only what the repository cannot give back: a delta tree (changed and
untracked files, deletions, empty directories), no git-ignored or oversized untracked files, and a
bundle of `base_sha..HEAD` (see docs/wait-workspace-checkpoints.md). When it does not replay to the
same fingerprint the full form is kept (`slim_failed`). The full form: directories regenerated by a
build (`DEFAULT_EXCLUDE_NAMES`, or the configured list) that hold no tracked file are left out of the
tree, the fingerprint and the status hash, and the manifest records which paths were left out
(`excludes`, always written, empty when nothing was left out). A manifest without `excludes` is the
oldest format and is replayed in full. A slim bundle's base is resolved in the object store recorded
at capture (`objects`: a pool slot's is its base clone's, which outlives the slot). Configured
submodules (empty or populated, one level) are captured with their own bundle/index and replayed
into the target's private modules directory. Unsupported nested repositories, recursive
submodules, special files and split indexes fail closed. Checkpoints are
retained after restore, including failures, for operator recovery.
"""

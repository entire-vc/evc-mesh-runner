def _sync(path: Path) -> None:
    fd = os.open(path, os.O_RDONLY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


def atomic_json(path: Path, value: dict) -> None:
    tmp = path.with_suffix('.tmp')
    with open(tmp, 'w', opener=lambda p, f: os.open(p, f, 0o600)) as out:
        json.dump(value, out, sort_keys=True)
        out.flush()
        os.fsync(out.fileno())
    os.replace(tmp, path)
    _sync(path.parent)


NESTED = 'repo'     # third field of a directory entry that holds a repository of its own (see `inventory`)


def nested_repos(tree: dict) -> list:
    """Roots of the repositories nested in untracked paths, as an inventory marks them."""
    return sorted(n for n, v in tree.items() if v[0] == 'dir' and len(v) > 2 and v[2] == NESTED)


def _varint(raw: bytes, pos: int, end: int) -> tuple:
    """git's offset varint (index v4 path prefix): (value, next position), or (None, pos) when cut off."""
    if pos >= end:
        return None, pos
    c = raw[pos]
    pos += 1
    value = c & 127
    while c & 128:
        if pos >= end:
            return None, pos
        c = raw[pos]
        pos += 1
        value = ((value + 1) << 7) + (c & 127)
    return value, pos


def _index_parses(raw: bytes, size: int) -> bool:
    """Every entry the header counts, then the extensions, end exactly where the `size`-byte trailer starts."""
    version, count, end, pos, previous = int.from_bytes(raw[4:8], 'big'), int.from_bytes(raw[8:12], 'big'), \
        len(raw) - size, 12, b''
    fixed = 40 + size + 2           # stat data, object id, flags
    for _ in range(count):
        start = pos
        if pos + fixed > end:
            return False
        flags = int.from_bytes(raw[pos + fixed - 2:pos + fixed], 'big')
        pos += fixed + (2 if flags & 0x4000 else 0)     # extended flags
        if version == 4:
            strip, pos = _varint(raw, pos, end)
            if strip is None or strip > len(previous):
                return False
        nul = raw.find(b'\0', pos, end)
        if nul < 0:
            return False
        name = previous[:len(previous) - strip] + raw[pos:nul] if version == 4 else raw[pos:nul]
        if version == 4:
            pos = nul + 1
        else:
            pos = start + ((nul - start + 8) & ~7)      # one to eight NULs to an 8-byte boundary
            if pos > end or raw[nul:pos].strip(b'\0'):
                return False
        if not name or (flags & 0xFFF) not in (len(name), 0xFFF) or (flags & 0xFFF == 0xFFF and len(name) < 0xFFF):
            return False
        previous = name
    while pos < end:                # extensions: signature, length, body
        if pos + 8 > end:
            return False
        pos += 8 + int.from_bytes(raw[pos + 4:pos + 8], 'big')
    return pos == end


def _index_skiphash(path: Path) -> bool:
    """git wrote this index with `index.skipHash`: an all-zero trailer, which proves nothing of its entries."""
    try:
        with path.open('rb') as f:
            f.seek(-20, os.SEEK_END)
            return f.read(20) == bytes(20)
    except OSError:
        return False


def _index_whole(path: Path, digest: str | None = None) -> bool:
    """A git index file as the capture stored it. With the capture's sha256 `digest` the bytes are
    compared exactly. Without it, as git writes one: the `DIRC` signature, version
    2 to 4, and the trailing checksum of everything before it (SHA-1 or SHA-256, by the repository's object
    format). An all-zero trailer (git's `index.skipHash`) proves nothing, so then every counted entry and
    extension must end exactly at the trailer; a damage that keeps the form is found only by the digest
    or, for a snapshot without one, by a replay (`Checkpoints.preflight`)."""
    try:
        raw = path.read_bytes()
    except OSError:
        return False
    if digest is not None:
        return hashlib.sha256(raw).hexdigest() == digest
    if len(raw) < 12 + 20 or raw[:4] != b'DIRC' or int.from_bytes(raw[4:8], 'big') not in (2, 3, 4):
        return False
    for algo, size in (('sha1', 20), ('sha256', 32)):
        if len(raw) < 12 + size:
            continue
        if raw[-size:] == bytes(size):
            if _index_parses(raw, size):
                return True
        elif hashlib.new(algo, raw[:-size]).digest() == raw[-size:]:
            return True
    return False


def inventory(root: Path, submodules: tuple = (), excludes: frozenset = frozenset(),
              nested_limit: int | None = None) -> dict:
    """Hash contents/modes without following links; reject sockets/devices.

    `submodules` lists the worktree paths whose `.git` pointer file is replaced on restore.
    `excludes` lists relative directory paths left out of the snapshot (not walked, not hashed).
    A directory holding a `.git` of its own (other than a listed submodule) is a nested repository:
    its entry is marked `['dir', mode, 'repo']` and everything beneath it, its `.git` included, is
    recorded as plain data. With `nested_limit`, a nested repository whose files add up to more than
    that many bytes fails before the rest of it is hashed.
    """
    result = {}
    pointers = {f'{p}/.git' for p in submodules}
    def walk(path: Path, repo: str | None = None, used: list | None = None):
        for child in sorted(path.iterdir()):
            name = child.relative_to(root).as_posix()
            if name in excludes or (name == '.git' and repo is None):
                continue
            s = child.lstat()
            if name in pointers and stat.S_ISREG(s.st_mode):
                continue
            mode = stat.S_IMODE(s.st_mode)
            if stat.S_ISLNK(s.st_mode):
                result[name] = ['link', mode, os.readlink(child)]
            elif stat.S_ISDIR(s.st_mode):
                if repo is None and os.path.lexists(child / '.git') and f'{name}/.git' not in pointers:
                    result[name] = ['dir', mode, NESTED]
                    walk(child, name, [0])
                else:
                    result[name] = ['dir', mode]
                    walk(child, repo, used)
            elif stat.S_ISREG(s.st_mode):
                if used is not None:
                    used[0] += s.st_size
                    if nested_limit is not None and used[0] > nested_limit:
                        raise CheckpointNestedTooLarge(
                            f'checkpoint: nested repository {repo}/ holds more than {nested_limit} bytes '
                            f'(limit per nested repository); lease retained')
                h = hashlib.sha256()
                with child.open('rb') as stream:
                    for block in iter(lambda: stream.read(1024 * 1024), b''):
                        h.update(block)
                result[name] = ['file', mode, s.st_size, h.hexdigest()]
            else:
                raise WorkspaceError(f'checkpoint: special file unsupported: {name}')
    walk(root)
    return result


def _modules_dir(path: Path) -> Path:
    modules = Path(git(path, 'rev-parse', '--git-path', 'modules'))
    return modules if modules.is_absolute() else path / modules


def _gitdir(gd: Path, *args: str, check: bool = True) -> str:
    r = _run(['git', '--git-dir', str(gd), '--work-tree', str(gd), *args], capture_output=True, text=True,
                       errors='surrogateescape')
    if check and r.returncode:
        raise WorkspaceError(f'checkpoint: git {args[0]} failed in a submodule gitdir: {r.stderr.strip()[:120]}')
    return r.stdout.strip()


def _submodule_index(gd: Path, index: Path) -> bytes:
    env = dict(os.environ, GIT_INDEX_FILE=str(index))
    r = _run(['git', '--git-dir', str(gd), '--work-tree', str(gd), 'ls-files', '--stage', '-z'],
             capture_output=True, env=env)
    if r.returncode:
        raise WorkspaceError('checkpoint: cannot inspect submodule index')
    return r.stdout


def _stash_create(repo: Path) -> str:
    """`git stash create`, also for an index holding intent-to-add (`git add -N`) entries.

    Git refuses to stash those ("Entry ... not uptodate. Cannot merge."), which kept the
    workspace from suspending. Retry on a scratch copy of the index in which those
    paths are really added; the real index is untouched (the checkpoint stores it as is).
    """
    try:
        return git(repo, 'stash', 'create')
    except WorkspaceError:
        # read the NUL-separated list raw: git() strips its output, which would cut a
        # leading space from the first path
        res = _run(['git', '-C', str(repo), 'diff', '--name-only', '-z', '--diff-filter=A'],
                             capture_output=True, text=True, errors='surrogateescape',
                             env=dict(os.environ, GIT_TERMINAL_PROMPT='0'), timeout=600)
        added = [n for n in res.stdout.split('\0') if n] if res.returncode == 0 else []
        if not added:
            raise
    index = Path(git(repo, 'rev-parse', '--git-path', 'index'))
    if not index.is_absolute():
        index = repo / index
    with tempfile.TemporaryDirectory(prefix='.ita-index-') as scratch:
        tmp = Path(scratch) / 'index'
        shutil.copy2(index, tmp)
        env = dict(os.environ, GIT_INDEX_FILE=str(tmp))
        git(repo, 'add', '-f', '--', *added, env=env)
        return git(repo, 'stash', 'create', env=env)


def _safe_rel(name: str) -> bool:
    p = Path(name)
    return bool(name) and not p.is_absolute() and '..' not in p.parts and '.git' not in p.parts


def _valid_tree_name(name, roots: set) -> bool:
    """A manifest path stays inside the tree; a `.git` component is allowed only inside a nested repository."""
    if not isinstance(name, str) or not name or '\0' in name:
        return False
    p = Path(name)
    # canonical relative form only: no absolute path, `..`, `.`, empty or doubled components
    if p.is_absolute() or '..' in p.parts or not p.parts or name != '/'.join(p.parts):
        return False
    if '.git' not in p.parts:
        return True
    return any('/'.join(p.parts[:i]) in roots for i in range(1, len(p.parts)))


def _submodule_names(source: Path) -> dict:
    """gitlink path -> submodule name, from the worktree .gitmodules (never from config values)."""
    r = _run(['git', '-C', str(source), 'config', '-f', '.gitmodules', '-z',
                        '--get-regexp', '^submodule\\..*\\.path$'], capture_output=True)
    if r.returncode not in (0, 1):
        raise WorkspaceError('checkpoint: configured submodule metadata unsupported')
    names = {}
    for item in r.stdout.split(b'\0'):
        if not item:
            continue
        key, _, value = item.partition(b'\n')
        try:
            names[value.decode('utf-8')] = key.decode('utf-8')[len('submodule.'):-len('.path')]
        except UnicodeDecodeError:
            raise WorkspaceError(f'checkpoint: non-UTF8 gitlink path unsupported: {value!r}') from None
    return names


def submodule_plan(source: Path) -> list:
    """Validate gitlinks and return one entry per configured submodule (empty for placeholders).

    Absent/empty placeholders without any submodule metadata need no external repo data: the
    parent commit/index preserves their OIDs. Configured submodules are supported one level deep
    when every gitlink maps to a `.gitmodules` name and its gitdir lives in this worktree's own
    modules directory. Never follow a symlink or claim an unverifiable state was checkpointed.
    """
    result = _run(['git', '-C', str(source), 'ls-files', '--stage', '-z'],
                            capture_output=True)
    if result.returncode:
        raise WorkspaceError('checkpoint: cannot inspect gitlinks')
    records = [record for record in result.stdout.split(b'\0') if record.startswith(b'160000 ')]
    head = _run(['git', '-C', str(source), 'ls-tree', '-r', '-z', 'HEAD'], capture_output=True)
    if head.returncode:
        raise WorkspaceError('checkpoint: cannot inspect HEAD gitlinks')
    head_links = {r.split(b'\t', 1)[1] for r in head.stdout.split(b'\0') if r.startswith(b'160000 ')}
    index_links = {r.split(b'\t', 1)[1] for r in records}
    if head_links - index_links:
        gone = ', '.join(sorted(l.decode('utf-8', 'replace') for l in head_links - index_links))
        raise WorkspaceError(f'checkpoint: removed or replaced gitlink unsupported: {gone}')
    if not records:
        return []
    configured = _run(['git', '-C', str(source), 'config',
                                 '--name-only', '--get-regexp', '^submodule\\.'], capture_output=True)
    if configured.returncode not in (0, 1):
        raise WorkspaceError('checkpoint: cannot inspect submodule configuration')
    modules = _modules_dir(source)
    metadata = bool(os.path.lexists(source / '.gitmodules') or configured.stdout
                    or git(source, 'ls-files', '--', '.gitmodules')
                    or git(source, 'ls-tree', '--name-only', 'HEAD', '.gitmodules')
                    or os.path.lexists(modules))
    names = _submodule_names(source) if metadata and os.path.lexists(source / '.gitmodules') else {}
    plan = []
    for record in records:
        header, raw_name = record.split(b'\t', 1)
        try:
            name = Path(raw_name.decode('utf-8'))
        except UnicodeDecodeError:
            raise WorkspaceError(f'checkpoint: non-UTF8 gitlink path unsupported: {raw_name!r}') from None
        if header.split()[2] != b'0' or name.is_absolute() or '..' in name.parts:
            raise WorkspaceError(f'checkpoint: unmerged or unsafe gitlink unsupported: {name.as_posix()}')
        populated = False
        current = source
        for part in name.parts:
            current = current / part
            try:
                mode = current.lstat().st_mode
            except FileNotFoundError:
                break  # absent placeholder, including an absent parent
            if not stat.S_ISDIR(mode):
                raise WorkspaceError(f'checkpoint: symlink or non-directory gitlink unsupported: {name.as_posix()}')
        else:
            populated = any(current.iterdir())
        if not metadata:
            if populated:
                raise WorkspaceError(f'checkpoint: populated submodule unsupported: {name.as_posix()}')
            continue
        sub = name.as_posix()
        if sub not in names or not _safe_rel(names[sub]) or '.git' in Path(sub).parts:
            raise WorkspaceError(f'checkpoint: configured submodule metadata unsupported: {sub}')
        plan.append({'path': sub, 'name': names[sub], 'populated': populated,
                     'gitdir': os.path.lexists(modules / names[sub])})
    if not metadata:
        return []
    # Everything under our modules directory must belong to a listed gitlink.
    known = {Path(e['name']).parts[0] for e in plan}
    if os.path.lexists(modules):
        if modules.is_symlink() or not modules.is_dir():
            raise WorkspaceError(f'checkpoint: configured submodule metadata unsupported: {modules}')
        stray = sorted(child.name for child in modules.iterdir() if child.name not in known)
        if stray:
            raise WorkspaceError(f"checkpoint: configured submodule metadata unsupported: {modules}/{stray[0]}")
    _check_locks(source, modules, plan)
    for e in plan:
        gd = modules / e['name']
        wt = source / e['path']
        if e['gitdir']:
            for part in [gd, *gd.parents]:
                if part == modules.parent:
                    break
                if part.is_symlink():
                    raise WorkspaceError(f"checkpoint: symlinked submodule gitdir unsupported: {e['path']}")
            if not gd.is_dir() or os.path.lexists(gd / 'modules'):
                raise WorkspaceError(f"checkpoint: recursive submodule unsupported: {e['path']}")
        if e['populated']:
            pointer = wt / '.git'
            if pointer.is_dir() and not pointer.is_symlink():
                # A clone made in the gitlink's own path keeps its repository inside the worktree;
                # capture and replay know only the absorbed form under our modules directory.
                # `git submodule absorbgitdirs` moves it there (a copy when the slot and its admin
                # dir are on two volumes). Named apart: the lease stays until it is moved.
                raise WorkspaceError(f"checkpoint: populated submodule unsupported (embedded .git directory): "
                                     f"{e['path']}")
            if not e['gitdir'] or pointer.is_symlink() or not pointer.is_file() or pointer.stat().st_size > 4096:
                raise WorkspaceError(f"checkpoint: populated submodule unsupported: {e['path']}")
            text = pointer.read_text(errors='surrogateescape')
            if not text.startswith('gitdir: ') or '\n' in text.strip():
                raise WorkspaceError(f"checkpoint: populated submodule unsupported: {e['path']}")
            if os.path.realpath(wt / text[len('gitdir: '):].strip()) != os.path.realpath(gd):
                raise WorkspaceError(f"checkpoint: submodule gitdir outside own modules unsupported: {e['path']}")
            inner = _run(['git', '-C', str(wt), 'ls-files', '--stage', '-z'], capture_output=True)
            if inner.returncode:
                raise WorkspaceError(f"checkpoint: cannot inspect submodule: {e['path']}")
            if any(r.startswith(b'160000 ') for r in inner.stdout.split(b'\0')):
                raise WorkspaceError(f"checkpoint: recursive submodule unsupported: {e['path']}")
            if _gitdir(gd, 'rev-parse', '--verify', '-q', 'HEAD', check=False) == '':
                raise WorkspaceError(f"checkpoint: unborn submodule unsupported: {e['path']}")
        elif e['gitdir'] and _gitdir(gd, 'rev-parse', '--verify', '-q', 'HEAD', check=False) == '':
            raise WorkspaceError(f"checkpoint: unborn submodule unsupported: {e['path']}")
    return plan


def _check_locks(source: Path, modules: Path, plan: list) -> None:
    gitdirs = [Path(git(source, 'rev-parse', '--absolute-git-dir'))]
    gitdirs += [modules / e['name'] for e in plan if e['gitdir']]
    if any(os.path.lexists(g / lock) for g in gitdirs for lock in ('index.lock', 'HEAD.lock')):
        raise WorkspaceError('checkpoint: active git writer; lease retained')


def _gitdir_state(gd: Path) -> dict:
    """What a submodule's fingerprint records of its gitdir: HEAD, the branch it names, the refs."""
    return {'gitdir': True, 'head': _gitdir(gd, 'rev-parse', '--verify', 'HEAD'),
            'branch': _gitdir(gd, 'symbolic-ref', '--quiet', 'HEAD', check=False),
            'refs': hashlib.sha256('\n'.join(
                line[1:] for line in _gitdir(gd, 'for-each-ref', '--format=%(symref)|%(refname) %(objectname)',
                                              'refs/heads', 'refs/tags', 'refs/remotes').splitlines()
                if line.startswith('|')  # symbolic refs (origin/HEAD) are not bundled
            ).encode(errors='surrogateescape')).hexdigest()}


def _worktree_state(raw) -> dict:
    """What a submodule's fingerprint records of its worktree; `raw(*args)` hashes a git command's output."""
    return {'staged': raw('diff', '--cached', '--binary', '--no-ext-diff'),
            'unstaged': raw('diff', '--binary', '--no-ext-diff'),
            'status': raw('status', '--porcelain=v1', '-z', '--untracked-files=all')}


def _submodule_state(path: Path, entry: dict, modules: Path) -> dict:
    gd = modules / entry['name']
    if not os.path.lexists(gd):
        return {'gitdir': False}
    state = _gitdir_state(gd)
    wt = path / entry['path']
    if (wt / '.git').is_file():
        def raw(*args):
            r = _run(['git', '-C', str(wt), *args], capture_output=True)
            if r.returncode:
                raise WorkspaceError('checkpoint: cannot fingerprint submodule state')
            return hashlib.sha256(r.stdout).hexdigest()
        state.update(_worktree_state(raw))
    return state


def _packed_refs(gd: Path) -> dict:
    """refname -> object id as recorded in the gitdir's packed-refs (what a clone or a replay wrote)."""
    packed = {}
    try:
        for line in (gd / 'packed-refs').read_text(errors='surrogateescape').splitlines():
            if line and line[0] not in '#^' and ' ' in line:
                oid, _, name = line.partition(' ')
                packed[name] = oid
    except OSError:
        pass
    return packed


_FETCHED_TAG = re.compile(r"tag '(.+)' of ")


def _fetched_tags(gd: Path) -> dict:
    """refname -> object id of every tag the gitdir's last fetch received (FETCH_HEAD)."""
    fetched = {}
    try:
        text = (gd / 'FETCH_HEAD').read_text(errors='surrogateescape')
    except OSError:
        return fetched
    for line in text.splitlines():
        oid, _, rest = line.partition('\t')
        m = _FETCHED_TAG.match(rest.partition('\t')[2])
        if m and re.fullmatch(r'[0-9a-f]{40}|[0-9a-f]{64}', oid):
            fetched['refs/tags/' + m.group(1)] = oid
    return fetched


def _bundle_tags(bundle: Path) -> dict:
    """refname -> object id of the tags a snapshot bundle carries; empty when it cannot be read.
    Only consulted before the bundle is proven: the restore proves it before anything is set aside."""
    r = _run(['git', 'bundle', 'list-heads', str(bundle)], capture_output=True, text=True, errors='surrogateescape')
    if r.returncode:
        return {}
    tags = {}
    for line in r.stdout.splitlines():
        oid, _, name = line.partition(' ')
        if name.startswith('refs/tags/'):
            tags[name] = oid
    return tags


def _local_tag(gd: Path, tags: list, known_tags: dict | None) -> str:
    """Why one of the gitdir's tags is local work; empty when every tag only mirrors a remote.

    A tag is the remote's when its exact (name, object id) is recorded in packed-refs (a clone
    or a replay wrote it), or the incoming snapshot carries it unchanged (`known_tags`: the
    restore brings it back), or it names a commit a remote-tracking ref reaches (a lightweight
    tag fetched after the clone holds nothing but that name). An annotated tag carries its own
    message, so loose it also needs the last fetch to have received it (FETCH_HEAD). Anything
    else, and every tag on a commit no remote has, is someone's work."""
    packed = _packed_refs(gd)
    known = known_tags or {}
    fetched = None
    rest = [(n, o) for n, o in tags if packed.get(n) != o and known.get(n) != o]
    if not rest:
        return ''
    kinds = {}
    for line in _gitdir(gd, 'for-each-ref', '--format=%(refname) %(objecttype) %(*objecttype) %(*objectname)',
                        'refs/tags', check=False).splitlines():
        name, kind, peeled_kind, peeled = (line.rsplit(' ', 3) + ['', '', ''])[:4]
        kinds[name] = (kind, peeled_kind, peeled)
    commits = {}
    for n, o in rest:
        kind, peeled_kind, peeled = kinds.get(n, ('', '', ''))
        short = n[len('refs/tags/'):]
        if kind == 'commit':
            commits[n] = o
        elif kind == 'tag' and peeled_kind == 'commit':
            if fetched is None:
                fetched = _fetched_tags(gd)
            if fetched.get(n) != o:
                return f'local annotated tag {short}'
            commits[n] = peeled
        else:
            return f'local tag {short}'
    unpublished = set(_gitdir(gd, 'rev-list', *sorted(set(commits.values())), '--not', '--remotes',
                              check=False).split()) if commits else set()
    for n, c in commits.items():
        if c in unpublished:
            return f'local tag {n[len("refs/tags/"):]} on a commit no remote has'
    return ''


def _repo_unique_work(gd: Path, known_tags: dict | None = None) -> str:
    """Why this gitdir holds something no remote has; empty when it is only a clone of one.

    Strict about refs: a local branch must equal a remote-tracking branch of the same name, a
    tag must mirror the remote (`_local_tag`; `known_tags` are the tags the incoming snapshot
    carries), and no ref may live outside heads, tags and remotes. Every commit must also be
    reachable from a remote-tracking ref."""
    refs = []
    for line in _gitdir(gd, 'for-each-ref', '--format=%(refname) %(objectname)', check=False).splitlines():
        name, _, oid = line.rpartition(' ')
        refs.append((name, oid))
    if any(not n.startswith(('refs/heads/', 'refs/tags/', 'refs/remotes/')) for n, _ in refs):
        return 'extra refs such as a stash'
    remote = {(n.split('/', 3)[3], o) for n, o in refs if n.startswith('refs/remotes/') and n.count('/') >= 3}
    for n, o in refs:
        if n.startswith('refs/heads/') and (n[len('refs/heads/'):], o) not in remote:
            return f'local branch {n[len("refs/heads/"):]} is not a remote-tracking branch'
    tags = [(n, o) for n, o in refs if n.startswith('refs/tags/')]
    if tags:
        why = _local_tag(gd, tags, known_tags)
        if why:
            return why
    if not _gitdir(gd, 'rev-parse', '--verify', '-q', 'HEAD', check=False):
        return 'unborn HEAD'
    if _gitdir(gd, 'rev-list', '-n', '1', 'HEAD', '--branches', '--tags', '--not', '--remotes', check=False):
        return 'commits not on any remote'
    return ''


def _stale_submodule_work(target: Path, entry: dict, gd: Path, known_tags: dict | None = None) -> str:
    """Why a submodule left in a pooled slot may NOT be set aside; empty when it is disposable.

    Disposable means a leftover of an earlier lease: no nested submodule state anywhere (a
    nested level is refused, not inspected), every commit and ref also on a remote (or, for a
    tag, in the incoming snapshot: `known_tags`), and a worktree that is absent, empty or clean
    (nothing staged, modified or untracked). Anything else may be someone's work."""
    # Nested submodules are not inspected: any sign of one makes the leftover unsafe to set aside.
    if not gd.is_dir():
        return 'not a plain gitdir'
    if os.path.lexists(gd / 'modules'):
        return 'nested submodule state in the gitdir'
    why = _repo_unique_work(gd, known_tags)
    if why:
        return why
    wt = target / entry['path']
    if not os.path.lexists(wt):
        return ''
    if wt.is_symlink() or not wt.is_dir():
        return 'worktree is not a directory'
    if not any(wt.iterdir()):
        return ''
    pointer = wt / '.git'
    if pointer.is_symlink():
        return 'worktree .git is a symlink'
    if pointer.is_file():
        text = pointer.read_text(errors='surrogateescape')
        if (not text.startswith('gitdir: ') or '\n' in text.strip()
                or os.path.realpath(wt / text[len('gitdir: '):].strip()) != os.path.realpath(gd)):
            return 'worktree points at another gitdir'
    elif pointer.is_dir():
        if any(os.path.lexists(pointer / lock) for lock in ('index.lock', 'HEAD.lock')):
            return 'active git writer in the worktree'
        if os.path.lexists(pointer / 'modules'):
            return 'nested submodule state in the worktree repository'
        why = _repo_unique_work(pointer)
        if why:
            return 'worktree repository: ' + why
    else:
        return 'worktree holds files outside any repository'
    for root, dirs, files in os.walk(wt):
        progress.beat()
        if root == str(wt):
            dirs[:] = [d for d in dirs if d != '.git']
            files = [f for f in files if f != '.git']
        if '.git' in dirs or '.git' in files:
            return 'nested repository in the worktree'
    status = _run(['git', '--no-optional-locks', '-C', str(wt), 'status', '--porcelain=v1', '-z',
                             '--untracked-files=all'], capture_output=True)
    if status.returncode or status.stdout:
        return 'uncommitted or untracked work'
    return ''


def find_excludes(source: Path, names: tuple, submodules: list = ()) -> list:
    """Outermost directories called one of `names` with no tracked file beneath them.

    Also searches populated configured submodules for git-ignored directories matching `names`
    with no tracked file beneath them (only git-ignored ones: an unignored directory inside a
    submodule marks its gitlink dirty in the superproject's `git status`). Opaque nested
    repositories are never entered."""
    if not names:
        return []
    r = _run(['git', '-C', str(source), 'ls-files', '-z'], capture_output=True)
    if r.returncode:
        raise _CheckpointListError('tracked', 'ls-files', r)
    tracked = set()  # tracked directories, and gitlinks (a submodule's own files are not listed here)
    for item in r.stdout.split(b'\0'):
        if not item:
            continue
        full = Path(item.decode('utf-8', 'surrogateescape'))
        tracked.add(full.as_posix())
        tracked.update('/'.join(full.parts[:i]) for i in range(1, len(full.parts)))
    found = []
    def walk(path: Path):
        for child in sorted(path.iterdir()):
            if child.name == '.git' or child.is_symlink() or not child.is_dir():
                continue
            name = child.relative_to(source).as_posix()
            if (source / name / '.git').exists():
                # A populated submodule keeps its tracked files in its own repository (handled
                # separately below); a nested repository is stored whole (see `inventory`), so
                # nothing inside it is left out as regenerable.
                continue
            if child.name in names and name not in tracked:
                found.append(name)
            else:
                walk(child)
    walk(source)
    for entry in submodules:
        if not entry.get('populated'):
            continue
        sub_path = entry['path']
        sub = source / sub_path
        candidates = find_excludes(sub, names)
        if not candidates:
            continue
        # Only leave out directories that Git in the submodule already ignores: an unignored
        # untracked file inside a submodule makes the superproject report the gitlink dirty.
        # `--literal-pathspecs` prevents glob or pathspec-magic prefixes in filesystem paths
        # (e.g. `app/[slug]/node_modules`) from hiding unignored files as clean.
        st = _run(['git', '--literal-pathspecs', '-C', str(sub), 'status', '--porcelain=v1', '-z',
                   '--untracked-files=all', '--', *candidates], capture_output=True)
        if st.returncode:
            raise _CheckpointListError('changed', 'status', st)
        dirty = set()
        parts = st.stdout.split(b'\0')
        idx = 0
        while idx < len(parts):
            item = parts[idx]
            idx += 1
            if len(item) < 4:
                continue
            xy, rel = item[:2].decode(), item[3:].decode('utf-8', 'surrogateescape')
            dirty.add(rel)
            if 'R' in xy or 'C' in xy:
                idx += 1
        pre = sub_path + '/'
        for cand in candidates:
            if not any(d == cand or d.startswith(cand + '/') for d in dirty):
                found.append(pre + cand)
    return found


@lru_cache(maxsize=1)
def _clonefile():
    if sys.platform != 'darwin':
        return None
    libc = ctypes.CDLL(None, use_errno=True)
    clone = getattr(libc, 'clonefile', None)
    if clone is not None:
        clone.argtypes = (ctypes.c_char_p, ctypes.c_char_p, ctypes.c_int)
        clone.restype = ctypes.c_int
    return clone


COPY_CHUNK = 8 << 20                       # a portable copy of a large file beats after each chunk


def _copy_file(src, dst):
    """Clone on APFS in-process; portable copy when cloning is unavailable. A file larger than one
    chunk is copied chunk by chunk with a beat between chunks, so one large file on a slow volume
    does not freeze the lane's status row; anything smaller, and every special file, goes through
    shutil.copy2 as before."""
    progress.beat()                         # a large tree copies file by file
    clone = _clonefile()
    if clone is not None and clone(os.fsencode(src), os.fsencode(dst), 0) == 0:
        shutil.copystat(src, dst)
        return dst
    st = os.stat(src)
    if not stat.S_ISREG(st.st_mode) or st.st_size <= COPY_CHUNK:
        return shutil.copy2(src, dst)
    with open(src, 'rb') as fin, open(dst, 'wb') as fout:
        while chunk := fin.read(COPY_CHUNK):
            fout.write(chunk)
            progress.beat()
    shutil.copystat(src, dst)
    return dst


def manifest_digest(checkpoint: Path) -> str:
    """Hash a regular manifest without following a checkpoint/manifest symlink."""
    flags = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW
    root = os.open(checkpoint.parent, flags)
    try:
        directory = os.open(checkpoint.name, flags, dir_fd=root)
        try:
            fd = os.open('manifest.json', os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=directory)
            with os.fdopen(fd, 'rb') as stream:
                if not stat.S_ISREG(os.fstat(stream.fileno()).st_mode):
                    raise WorkspaceError('checkpoint pin: manifest is not a regular file')
                return hashlib.file_digest(stream, 'sha256').hexdigest()
        finally:
            os.close(directory)
    finally:
        os.close(root)


def _copy(src: Path, dst: Path, excludes: frozenset = frozenset()) -> None:
    shutil.copytree(src, dst, symlinks=True, copy_function=_copy_file,
                    ignore=lambda p, names: [n for n in names if (Path(p) == src and n == '.git')
                                             or (Path(p) / n).relative_to(src).as_posix() in excludes])


# Where a slim capture stopped. `_mark` records the stage last entered on this thread; the slim
# attempt reads it when it fails. Only these names are ever persisted or logged.
_TRACE = threading.local()
SLIM_STAGES = frozenset({
    'capture-plan', 'capture-copy', 'capture-stash', 'capture-refs', 'capture-bundle', 'capture-submodule',
    'verify-setup', 'verify-pack', 'verify-proof', 'verify-snapshot', 'verify-base', 'verify-fetch',
    'verify-checkout', 'verify-overlay', 'verify-index', 'verify-refresh', 'verify-fingerprint', 'source-recheck', 'unknown'})
SLIM_GIT_COMMANDS = frozenset({
    'bundle', 'cat-file', 'checkout', 'checkout-index', 'config', 'diff', 'fetch', 'init', 'ls-files', 'read-tree',
    'rev-list', 'rev-parse', 'stash', 'status', 'symbolic-ref', 'update-index', 'update-ref'})
# Fixed checkpoint messages, checked in order; the first fragment found names the class.
_SLIM_FIXED = (
    ('bundle base', 'bundle-base-unavailable'),
    ('replay verification failed', 'replay-mismatch'),
    ('snapshot hash mismatch', 'snapshot-mismatch'),
    ('base commit missing', 'base-commit-missing'),
    ('cannot fingerprint', 'fingerprint-git-failed'),
    ('cannot list', 'list-git-failed'),
    ('active git writer', 'git-writer-active'),
    ('delta path outside', 'unsafe-delta-path'),
    ('invalid manifest', 'invalid-manifest'),
    ('special file unsupported', 'special-file'),
    ('submodule', 'submodule'),
    ('disk availability unknown', 'disk-unknown'),
    ('bundle invalid', 'bundle-invalid'),
)
# What a failed git command said, reduced to a class (stderr itself is never kept).
_SLIM_GIT_ERRORS = (
    (('timed out',), 'timeout'),
    (('.lock', 'unable to create', 'cannot lock', 'file exists'), 'lock'),
    (('no space left',), 'no-space'),
    (('permission denied', 'operation not permitted'), 'permission'),
    (('bad object', 'unable to read', 'missing', 'not a valid', 'could not read', 'did not receive',
      'packfile', 'pack file', 'loose object', 'corrupt', 'invalid object', 'unable to parse'), 'object-unreadable'),
    (('not a git repository',), 'not-a-repository'),
    (('this operation must be run in a work tree',), 'not-a-work-tree'),
    (('unknown revision', 'ambiguous argument', 'bad revision', 'invalid reference'), 'revision-unknown'),
)
SLIM_REASONS = frozenset({kind for _, kind in _SLIM_FIXED} | {'git-' + kind for _, kind in _SLIM_GIT_ERRORS}
                         | {'git-other', 'timeout', 'other'})
_GIT_MESSAGE = re.compile(r'git (\S+)(?: .*?)? in .*?: (.*)\Z', re.S)


class _CheckpointListError(WorkspaceError):
    """Keep the failing operation/exit and a finite cause, never raw Git stderr."""

    def __init__(self, kind: str, command: str, result: subprocess.CompletedProcess):
        said = result.stderr.decode('utf-8', 'replace').lower()
        reason = next((kind for fragments, kind in _SLIM_GIT_ERRORS
                       if any(fragment in said for fragment in fragments)), 'other')
        self.reason = 'git-' + reason
        self.command = command
        # A process exit status: a small integer (negative = killed by that signal).
        code = result.returncode
        self.exit = code if isinstance(code, int) and -255 <= code <= 255 else None
        super().__init__(f'checkpoint: cannot list {kind} files: git={command} '
                         f'exit={result.returncode} reason={self.reason}')


def _mark(stage: str) -> None:
    _TRACE.stage = stage


def slim_failure_cause(error: Exception, stage: str | None = None) -> dict:
    """{'reason', 'stage', 'git', 'exit'} of a failed slim capture: finite allowlisted values only,
    never exception text, paths or command output. `git` is the failing git subcommand, or None;
    `exit` is its exit status when the failure carries one, or None."""
    if isinstance(error, _CheckpointListError):
        return {'reason': error.reason, 'stage': stage if stage in SLIM_STAGES else 'unknown',
                'git': error.command, 'exit': error.exit}
    message = str(error)
    reason, command = 'other', None
    lowered = message.lower()
    # Fixed texts only in this module's own messages: a git message carries arguments and paths.
    own = message.startswith('checkpoint:')
    fixed = next((kind for fragment, kind in _SLIM_FIXED if fragment in message), 'other') if own else None
    found = _GIT_MESSAGE.match(message) if not own else None
    if fixed is not None:
        reason = fixed
    elif found is not None:
        command = found.group(1) if found.group(1) in SLIM_GIT_COMMANDS else 'other'
        said = found.group(2).lower()
        reason = 'git-' + next((kind for fragments, kind in _SLIM_GIT_ERRORS
                                if any(f in said for f in fragments)), 'other')
    elif 'timed out' in lowered:
        reason = 'timeout'
    stage = stage if stage in SLIM_STAGES else 'unknown'
    reason = reason if reason in SLIM_REASONS else 'other'
    return {'reason': reason, 'stage': stage, 'git': command, 'exit': None}


def _exit_suffix(cause: dict) -> str:
    code = cause.get('exit')
    return f' exit={code}' if isinstance(code, int) else ''


def _slim_failure_reason(error: WorkspaceError) -> str:
    # Persist only a finite classification, never exception text, paths or command output.
    return slim_failure_cause(error)['reason']


def _same_volume(a: Path, b: Path) -> bool:
    """True when a file clone from `a` into `b` is possible (same filesystem); unknown counts as not."""
    try:
        return os.stat(a).st_dev == os.stat(b).st_dev
    except OSError:
        return False


def _rmtree(path, ignore_errors: bool = False) -> None:
    """shutil.rmtree with a beat per directory, so removing a large tree does not freeze the lane's
    status row. Directories are emptied bottom-up through os.fwalk (relative to open directory fds;
    no symlink is followed, a symlink root is never entered), granting owner rwx on each captured
    read-only directory; whatever that leaves (a refused unlink, a missing or symlinked root) goes
    to shutil.rmtree, which raises or ignores it as before."""
    try:
        for _root, dirs, files, dfd in os.fwalk(path, topdown=False):
            progress.beat()
            mode = stat.S_IMODE(os.fstat(dfd).st_mode)
            if mode & 0o700 != 0o700:
                os.fchmod(dfd, mode | 0o700)
            for name in files:
                os.unlink(name, dir_fd=dfd)
            for name in dirs:
                try:
                    os.rmdir(name, dir_fd=dfd)
                except NotADirectoryError:      # a symlink to a directory is listed in dirs
                    os.unlink(name, dir_fd=dfd)
    except OSError:
        pass
    shutil.rmtree(path, ignore_errors=ignore_errors)


def _clear_tree(root: Path) -> None:
    # Called only for an owned lease after a durable checkpoint; never on a base clone.
    for child in root.iterdir():
        if child.name == '.git':
            continue
        if child.is_dir() and not child.is_symlink():
            _rmtree(child)
        else:
            child.unlink()


def fingerprint(path: Path, submodules: list | None = None, excludes: tuple = (), ignored: tuple = (),
                nested_limit: int | None = None) -> dict:
    subs = submodules or []
    roots = tuple(e['path'] for e in subs if e['populated'])
    # Untracked-but-not-ignored excluded dirs show up in `status`; leave them out of it too.
    # Submodule-internal excludes are git-ignored inside their submodule and never passed as
    # superproject pathspecs across a gitlink boundary.
    outer_excludes = [e for e in excludes if not any(e == r or e.startswith(r + '/') for r in roots)]
    spec = ['--', '.', *(f':(exclude,literal){e}' for e in outer_excludes)] if outer_excludes else []
    def raw(*args):
        r = _run(['git', '-C', str(path), *args], capture_output=True)
        if r.returncode:
            raise WorkspaceError('checkpoint: cannot fingerprint git state')
        return hashlib.sha256(r.stdout).hexdigest()
    result = {'head': git(path, 'rev-parse', 'HEAD'),
              'staged': raw('diff', '--cached', '--binary', '--no-ext-diff'),
              'unstaged': raw('diff', '--binary', '--no-ext-diff'),
              'status': raw('status', '--porcelain=v1', '-z', '--untracked-files=all', *spec),
              'tree': inventory(path, roots, frozenset((*excludes, *ignored)), nested_limit)}
    if subs:
        modules = _modules_dir(path)
        result['submodules'] = {e['path']: _submodule_state(path, e, modules) for e in subs}
    return result


MAX_UNTRACKED_BYTES = 16 * 1024 * 1024    # an untracked file above this is not worth a snapshot slot
MAX_NESTED_REPO_BYTES = 256 * 1024 * 1024   # a repository nested in an untracked path is stored whole, up to this


def _status_entries(source: Path) -> list:
    """(XY, path, orig) for every changed/untracked path, as git sees it; ignored paths are absent."""
    r = _run(['git', '-C', str(source), 'status', '--porcelain=v1', '-z', '--untracked-files=all'],
                       capture_output=True)
    if r.returncode:
        raise _CheckpointListError('changed', 'status', r)
    parts = r.stdout.split(b'\0')
    out, i = [], 0
    while i < len(parts):
        item = parts[i]
        i += 1
        if len(item) < 4:
            continue
        xy, name = item[:2].decode(), item[3:].decode('utf-8', 'surrogateescape')
        orig = None
        if 'R' in xy or 'C' in xy:
            orig = parts[i].decode('utf-8', 'surrogateescape') if i < len(parts) else None
            i += 1
        out.append((xy, name, orig))
    return out


def find_ignored(source: Path, covered: list, submodules: list = ()) -> list:
    """Git-ignored paths (outermost), minus what a named exclude already covers: logs, caches and
    build output that any clone regenerates. Tracked files are never listed here.

    Also collects git-ignored paths inside populated configured submodules (prefixed with their
    gitlink path), so regenerable submodule caches are left out of slim snapshots too."""
    r = _run(['git', '-C', str(source), 'ls-files', '-z', '--others', '--ignored', '--exclude-standard',
                        '--directory'], capture_output=True)
    if r.returncode:
        raise _CheckpointListError('ignored', 'ls-files', r)
    found = []
    for item in r.stdout.split(b'\0'):
        name = item.decode('utf-8', 'surrogateescape').rstrip('/')
        if name and name != '.git' and not any(name == c or name.startswith(c + '/') for c in covered):
            found.append(name)
    for entry in submodules:
        if not entry.get('populated'):
            continue
        sub_path = entry['path']
        pre = sub_path + '/'
        sub_covered = [c[len(pre):] for c in covered if c.startswith(pre)]
        for name in find_ignored(source / sub_path, sub_covered):
            found.append(pre + name)
    return found


def find_large_untracked(source: Path, covered: list, limit: int) -> list:
    out = []
    for xy, name, _ in _status_entries(source):
        if xy != '??' or any(name == c or name.startswith(c + '/') for c in covered):
            continue
        try:
            if (source / name).lstat().st_size > limit and not (source / name).is_symlink():
                out.append(name)
        except OSError:
            pass
    return out


def _delta_plan(source: Path, before: dict, excludes: list, ignored: list, plan: list = ()) -> dict:
    """What the worktree holds that `checkout` of HEAD does not give back: changed/untracked files,
    paths deleted from the worktree and empty untracked directories. A superset is harmless; the
    capture-time replay proves the plan complete or the caller falls back to a full tree.

    A populated submodule is a repository of its own: its part of the delta is taken against its own
    HEAD (see `_repo_delta`), and the superproject's part stops at its gitlink. All paths are relative
    to `source`; `_split_delta` separates the parts again."""
    tree = before['tree']
    roots = [e['path'] for e in plan if e['populated']]
    files, deleted, dirs = _repo_delta(source, tree, [*excludes, *ignored], roots=roots)
    for root in roots:
        more = _repo_delta(source, tree, [], prefix=root)
        files |= more[0]
        deleted |= more[1]
        dirs |= more[2]
    return {'files': sorted(files), 'deleted': sorted(deleted), 'dirs': sorted(dirs)}


def _repo_delta(source: Path, tree: dict, skip: list, prefix: str = '', roots: list = ()) -> tuple:
    """(files, deleted, dirs) of one repository: the superproject (no `prefix`; nothing beneath the
    populated submodule `roots`) or the populated submodule at `prefix`. Any remaining non-tracked
    file still in `tree` beneath a submodule (git-ignored paths are already skipped in slim mode)
    is included as a superset safeguard."""
    repo = source / prefix if prefix else source
    pre = prefix + '/' if prefix else ''

    def mine(name: str) -> bool:
        return name.startswith(pre) if prefix else not any(name.startswith(r + '/') for r in roots)
    files, deleted = set(), set()
    for xy, name, orig in _status_entries(repo):
        name, orig = pre + name, (pre + orig if orig is not None else None)
        if any(name == c or name.startswith(c + '/') for c in skip):
            continue
        if orig is not None and not os.path.lexists(source / orig):
            deleted.add(orig)
        if os.path.lexists(source / name):
            if not (source / name).is_dir() or (source / name).is_symlink():
                files.add(name)
        else:
            deleted.add(name)
    r = _run(['git', '-C', str(repo), 'ls-files', '-z'], capture_output=True)
    if r.returncode:
        raise _CheckpointListError('tracked', 'ls-files', r)
    tracked, tracked_dirs = set(), set()
    for item in r.stdout.split(b'\0'):
        if not item:
            continue
        parts = Path(pre + item.decode('utf-8', 'surrogateescape')).parts
        tracked.add('/'.join(parts))
        tracked_dirs.update('/'.join(parts[:i]) for i in range(1, len(parts) + 1))   # a gitlink is a dir too
    scope = {k: v for k, v in tree.items() if mine(k)}
    # A nested repository is opaque: git lists it as one directory, so take every file beneath it.
    for root in nested_repos(scope):
        files.update(k for k, v in scope.items() if k.startswith(root + '/') and v[0] in ('file', 'link'))
    if prefix:
        files.update(k for k, v in scope.items() if v[0] in ('file', 'link') and k not in tracked)
    dirs = {n for n, v in scope.items() if v[0] == 'dir' and n not in tracked_dirs
            and not any(k.startswith(n + '/') for k in tree)}
    return files, deleted, dirs


def _split_delta(delta: dict, roots) -> tuple:
    """The superproject's part of a delta and {root: part} of each populated submodule's."""
    def part(keep) -> dict:
        return {key: [n for n in delta.get(key, []) if keep(n)] for key in ('files', 'deleted', 'dirs')}
    roots = tuple(roots)
    outer = part(lambda n: not any(n.startswith(r + '/') for r in roots))
    return outer, {r: part(lambda n, r=r: n.startswith(r + '/')) for r in roots}


def _delta_keep(full: dict, delta: dict) -> dict:
    """The part of the full inventory a delta tree holds: its files, their parent directories, its empty dirs."""
    keep = set(delta['files']) | set(delta['dirs'])
    for name in list(keep):
        parts = Path(name).parts
        keep.update('/'.join(parts[:i]) for i in range(1, len(parts)))
    return {k: v for k, v in full.items() if k in keep}


def _objects_dir(repo: Path) -> Path:
    objects = Path(git(repo, 'rev-parse', '--git-path', 'objects'))
    return objects if objects.is_absolute() else repo / objects


class CheckpointBaseMissing(WorkspaceError):
    """The base commit a snapshot (or its compacted form) needs is absent from the durable object store.
    Retrying cannot help: the snapshot stays restorable only where the base still is."""


def base_objects_dir(repo: Path, env: dict | None = None) -> Path | None:
    """Object directory of a repository (a worktree resolves to its common one); None when unreadable."""
    try:
        objects = Path(git(repo, 'rev-parse', '--git-path', 'objects', env=env))
    except (WorkspaceError, OSError):
        return None
    return objects if objects.is_absolute() else Path(repo) / objects


def _durable_objects(data: dict, fallback: Path | None = None) -> Path | None:
    """Where a snapshot's bundle base lives: the object store recorded at capture, else the caller's
    (a pool passes its base clone's), else the capture source's if it still exists."""
    for candidate in (data.get('objects'), fallback):
        if candidate and Path(candidate).is_dir():
            return Path(candidate)
    source = Path(data['source'])
    found = base_objects_dir(source) if source.is_dir() else None
    return found if found is not None and found.is_dir() else None


def _has_commit(repo: Path, sha: str) -> bool:
    return _run(['git', '-C', str(repo), 'cat-file', '-e', f'{sha}^{{commit}}'],
                          capture_output=True).returncode == 0



def _config_reason(name: str) -> str:
    """`config <section>.<key>`: the subsection (a URL, a driver name) never goes into a log line."""
    section, _, rest = name.partition('.')
    return f"config {section}.{rest.rsplit('.', 1)[-1]}" if rest else f'config {section}'


def _git_bool(value: str | None) -> bool | None:
    """A config value read as Git reads a boolean: no `=` is true, an empty value false; None when it
    is not a boolean."""
    if value is None:
        return True
    v = value.strip().lower()
    if v in ('true', 'yes', 'on'):
        return True
    if v in ('false', 'no', 'off', ''):
        return False
    try:
        return int(v, 0) != 0
    except ValueError:
        return None


def _parents(name: str) -> list:
    parts = name.split('/')
    return ['/'.join(parts[:i]) for i in range(1, len(parts))]


def _blob_digests(repo: Path, oids: list, keep: set, timeout: float = 600, env: dict | None = None) -> dict:
    """oid -> (size, sha256 of the raw content, the content itself when the oid is in `keep`), read
    through one `git cat-file --batch`: no file is written and nothing is held in memory but `keep`."""
    if not oids:
        return {}
    proc = subprocess.Popen(['git', '-C', str(repo), 'cat-file', '--batch'], stdin=subprocess.PIPE,
                            stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                            env=env if env is not None else dict(os.environ, **_READ_ONLY_GIT))
    timer = threading.Timer(timeout, proc.kill)     # a killed reader ends the stream: the proof fails
    timer.daemon = True
    timer.start()

    def feed():
        try:
            for oid in oids:
                proc.stdin.write(oid.encode('ascii') + b'\n')
            proc.stdin.close()
        except (BrokenPipeError, OSError, ValueError):
            pass
    writer = threading.Thread(target=feed, daemon=True)
    writer.start()
    out = {}
    try:
        for oid in oids:
            header = proc.stdout.readline().split()
            if len(header) != 3 or header[0].decode('ascii', 'replace') != oid or header[1] != b'blob':
                raise _NotProvable('object')
            size = remaining = int(header[2])
            digest, kept = hashlib.sha256(), [] if oid in keep else None
            while remaining:
                chunk = proc.stdout.read(min(remaining, 1 << 20))
                if not chunk:
                    raise _NotProvable('object')
                digest.update(chunk)
                if kept is not None:
                    kept.append(chunk)
                remaining -= len(chunk)
            if proc.stdout.read(1) != b'\n':
                raise _NotProvable('object')
            out[oid] = (size, digest.hexdigest(), b''.join(kept) if kept is not None else None)
        return out
    finally:
        timer.cancel()
        proc.kill()
        try:
            proc.wait(timeout=5)
        except subprocess.TimeoutExpired:
            pass
        for stream in (proc.stdin, proc.stdout):
            try:
                stream.close()
            except OSError:
                pass



class Checkpoints:
    def __init__(self, root: Path, reserve_bytes: int = 512 * 1024 * 1024, *, capture_min_free_bytes: int = 0,
                 exclude_names: tuple = DEFAULT_EXCLUDE_NAMES, slim: bool = True,
                 max_untracked_bytes: int = MAX_UNTRACKED_BYTES, max_nested_bytes: int | None = None):
        self.root = root
        self.max_nested_bytes = MAX_NESTED_REPO_BYTES if max_nested_bytes is None else max_nested_bytes
        self.slim = slim
        self.max_untracked_bytes = max_untracked_bytes
        self.exclude_names = tuple(exclude_names)
        self.reserve_bytes = reserve_bytes
        self.capture_min_free_bytes = capture_min_free_bytes
        root.mkdir(parents=True, exist_ok=True, mode=0o700)
        root.chmod(0o700)

    def _budget(self, target: Path, needed: int, min_free_bytes: int = 0) -> None:
        try:
            free = shutil.disk_usage(target).free
        except OSError:
            raise WorkspaceError('checkpoint: disk availability unknown; lease retained') from None
        if free < needed + max(self.reserve_bytes, min_free_bytes):
            raise WorkspaceError('checkpoint: insufficient disk budget; lease retained')

    def create(self, key: str, source: Path, metadata: dict) -> Path:
        with _IO_LOCK:
            return self._create_best(key, source, metadata)

    def _create_best(self, key: str, source: Path, metadata: dict) -> Path:
        if not self.slim:
            return self._create(key, source, metadata, slim=False)
        _mark('capture-plan')
        try:
            return self._create(key, source, metadata, slim=True)
        except WorkspaceError as e:
            if (isinstance(e, CheckpointNestedTooLarge) or 'insufficient disk' in str(e)
                    or 'source changed' in str(e) or 'unsupported' in str(e)):
                raise
            cause = slim_failure_cause(e, getattr(_TRACE, 'stage', None))
        # The compact form did not replay to the same state (filters, skip-worktree, a missing base).
        # The full form is always self-contained, but it is only cheap where the tree can be cloned:
        # across volumes it is a real copy of the whole worktree on the checkpoint volume, every time.
        # There the lease is kept instead (the slot stays where it is, the next suspend pass retries).
        if not _same_volume(source, self.root):
            self._log_slim_fallback(metadata, cause, 'lease-retained')
            raise WorkspaceError(f"checkpoint: slim capture failed ({cause['stage']}/{cause['reason']}"
                                 f"{_exit_suffix(cause)}); "
                                 "a full copy would cross volumes; lease retained")
        path = self._create(key, source, metadata, slim=False, slim_failed=True, slim_failure=cause)
        self._log_slim_fallback(metadata, cause, 'full-form')
        return path

    def _log_slim_fallback(self, metadata: dict, cause: dict, outcome: str) -> None:
        # One line per fallback, from allowlisted values and ids only.
        def ident(value) -> str:
            text = str(value or '')[:8]
            return text if re.fullmatch(r'[0-9a-f]{1,8}', text) else '-'
        repo = str(metadata.get('repo') or '')
        repo = repo if re.fullmatch(r'[A-Za-z0-9._-]{1,64}', repo) else '-'
        code = cause.get('exit')
        log.warning("checkpoint slim fallback: agent=%s card=%s attempt=%s repo=%s stage=%s reason=%s git=%s "
                    "exit=%s outcome=%s",
                    self.root.name, ident(metadata.get('task')), ident(metadata.get('attempt')), repo,
                    cause['stage'], cause['reason'], cause['git'] or '-',
                    code if isinstance(code, int) else '-', outcome)

    def _create(self, key: str, source: Path, metadata: dict, slim: bool = False, slim_failed: bool = False,
                slim_failure: dict | None = None) -> Path:
        if not key or any(c not in 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_' for c in key):
            raise WorkspaceError('checkpoint: invalid key')
        final = self.root / key
        if final.exists():
            self.verify(final)
            return final
        plan = submodule_plan(source)
        if git(source, 'rev-parse', '--shared-index-path'):
            raise WorkspaceError('checkpoint: split index unsupported')
        excludes = find_excludes(source, self.exclude_names, plan)
        ignored = []
        if slim:
            ignored = find_ignored(source, excludes, plan)
            excludes += find_large_untracked(source, [*excludes, *ignored], self.max_untracked_bytes)
        before = fingerprint(source, plan, tuple(excludes), tuple(ignored), self.max_nested_bytes)
        delta = _delta_plan(source, before, excludes, ignored, plan) if slim else None
        if submodule_plan(source) != plan:
            raise WorkspaceError('checkpoint: source changed during capture; lease retained')
        modules = _modules_dir(source)
        size = sum(v[2] for v in before['tree'].values() if v[0] == 'file')
        stored = sum(before['tree'][n][2] for n in delta['files'] if before['tree'][n][0] == 'file') if delta else size
        # Full history bundle can be larger than the worktree; count the shared object store.
        objects = Path(git(source, 'rev-parse', '--git-path', 'objects'))
        if not objects.is_absolute():
            objects = source / objects
        object_size = sum(p.stat().st_size for p in objects.rglob('*') if p.is_file())
        object_size += sum(p.stat().st_size for e in plan if e['gitdir']
                           for p in (modules / e['name']).rglob('*') if p.is_file() and not p.is_symlink())
        # Snapshot plus scratch replay: two trees, the saved bundle and the
        # replay's object store. Budget one new capture, not every waiting slot.
        self._budget(self.root, size + stored + 3 * object_size, self.capture_min_free_bytes)
        pending = Path(tempfile.mkdtemp(prefix='.pending-', dir=self.root))
        pending.chmod(0o700)
        try:
            _mark('capture-copy')
            if delta is not None:
                self._copy_delta(source, pending / 'tree', before['tree'], delta)
            else:
                _copy(source, pending / 'tree', frozenset((*excludes, *ignored)))
            index = Path(git(source, 'rev-parse', '--git-path', 'index'))
            if not index.is_absolute():
                index = source / index
            shutil.copy2(index, pending / 'index')
            # HEAD alone omits blobs referenced only by the staged index. A stash
            # commit records them without changing HEAD/index/worktree; keep its ref.
            _mark('capture-stash')
            stash = _stash_create(source)
            _mark('capture-refs')
            refs = ['HEAD']
            base_sha = metadata.get('base_sha')
            ref = None
            if base_sha:
                base_ref = f'refs/runner-checkpoint-bases/{key}'
                git(source, 'update-ref', base_ref, base_sha)
                refs.append(base_ref)
            if stash:
                ref = f'refs/runner-checkpoints/{key}'
                git(source, 'update-ref', ref, stash)
                refs.append(ref)
            _mark('capture-bundle')
            bundle = self._bundle(source, pending, refs, base_sha if slim else None, stash and ref)
            (pending / 'index').chmod(0o600)
            _mark('capture-submodule')
            for i, entry in enumerate(plan):
                if entry['gitdir']:
                    self._capture_submodule(key, source, modules, entry, pending / 'submodules' / str(i))
            branch = git(source, 'symbolic-ref', '--quiet', 'HEAD', check=False) or None
            # `objects` outlives the source when that is a pool slot: a slot shares its base clone's store.
            # `excludes` is written even when empty: its absence marks the oldest format.
            # 3: a delta that holds a populated submodule's part, which an older runner cannot replay
            # (it never checks a submodule's HEAD out); it refuses the manifest instead of a wrong tree.
            version = 3 if delta is not None and any(e['populated'] for e in plan) else 2 if plan else 1
            manifest = {'version': version, 'source': str(source), 'metadata': metadata, 'branch': branch,
                        'base_sha': metadata.get('base_sha', before['head']), 'fingerprint': before,
                        'bytes': size, 'object_bytes': object_size, 'objects': str(objects),
                        'excludes': excludes}
            if ignored:
                manifest['ignored'] = ignored
            if slim_failed:
                manifest['slim_failed'] = True      # full form kept on purpose: not a migration candidate
                cause = slim_failure or {'reason': 'other', 'stage': 'unknown', 'git': None}
                manifest['slim_failure_reason'] = cause['reason']
                manifest['slim_failure_stage'] = cause['stage']
                if cause.get('git'):
                    manifest['slim_failure_git'] = cause['git']
                if isinstance(cause.get('exit'), int):
                    manifest['slim_failure_exit'] = cause['exit']
            if delta is not None:
                manifest['delta'] = delta
                manifest['stored_bytes'] = stored
            if bundle:
                manifest['bundle'] = bundle
            if plan:
                manifest['submodules'] = plan
            # what each stored index was: an adoption checks them exactly, without a replay (preflight)
            manifest['index_sha256'] = {
                str(f.relative_to(pending)): hashlib.sha256(f.read_bytes()).hexdigest()
                for f in [pending / 'index', *(pending / 'submodules' / str(i) / 'index' for i in range(len(plan)))]
                if f.is_file()}
            atomic_json(pending / 'manifest.json', manifest)
            # Other writers can consume space during copying. Recheck before
            # scratch allocation; failure removes only this pending copy.
            self._budget(self.root, size + 2 * object_size, self.capture_min_free_bytes)
            self.verify(pending, in_place=True)
            _mark('source-recheck')
            if submodule_plan(source) != plan or fingerprint(source, plan, tuple(excludes), tuple(ignored), self.max_nested_bytes) != before:
                raise WorkspaceError('checkpoint: source changed during capture; lease retained')
            # fsync all regular files before publishing the checkpoint directory.
            for p in pending.rglob('*'):
                if p.is_file() and not p.is_symlink():
                    _sync(p)
            for p in sorted((p for p in pending.rglob('*') if p.is_dir() and not p.is_symlink()), reverse=True):
                _sync(p)
            _sync(pending)
            os.rename(pending, final)
            _sync(self.root)
            return final
        except Exception:
            # A partial capture has no authority; source is untouched. Do not accumulate
            # full-tree temporary copies on every poll after a verification failure.
            _rmtree(pending, ignore_errors=True)
            raise

    def _bundle(self, source: Path, pending: Path, refs: list, base_sha: str | None, stash_ref: str | None):
        """Write commits.bundle. Slim form: only what `base_sha` (pinned by a checkpoint ref) lacks, with
        base_sha as the bundle's prerequisite; None when the full-history form was written."""
        out = pending / 'commits.bundle'
        known = base_sha and _run(['git', '-C', str(source), 'cat-file', '-e', f'{base_sha}^{{commit}}'],
                                            capture_output=True).returncode == 0
        if not known:
            git(source, 'bundle', 'create', str(out), *refs)
            out.chmod(0o600)
            return None
        has_head = bool(git(source, 'rev-list', '-n1', 'HEAD', f'^{base_sha}'))
        positive = (['HEAD'] if has_head else []) + ([stash_ref] if stash_ref else [])
        info = {'mode': 'incremental' if positive else 'none', 'base': base_sha, 'has_head': has_head}
        if positive:
            git(source, 'bundle', 'create', str(out), *positive, f'^{base_sha}')
            out.chmod(0o600)
        return info

    def _copy_delta(self, source: Path, dst: Path, full: dict, delta: dict) -> None:
        """Copy only the delta files (APFS clones where possible), parents with their recorded modes."""
        dst.mkdir()
        dirs = set(delta['dirs'])
        # Parents of an empty kept directory are part of the snapshot too (`_delta_keep`): without
        # their recorded modes a 0700 parent comes out 0755 and the capture never verifies.
        for name in delta['dirs']:
            dirs.update('/'.join(Path(name).parts[:i]) for i in range(1, len(Path(name).parts)))
        for name in delta['files']:
            src, out = source / name, dst / name
            dirs.update('/'.join(Path(name).parts[:i]) for i in range(1, len(Path(name).parts)))
            out.parent.mkdir(parents=True, exist_ok=True)
            if src.is_symlink():
                os.symlink(os.readlink(src), out)
                shutil.copystat(src, out, follow_symlinks=False)
            else:
                _copy_file(src, out)
        for name in sorted(dirs, key=lambda n: -len(Path(n).parts)):
            (dst / name).mkdir(parents=True, exist_ok=True)
            if name in full:
                (dst / name).chmod(full[name][1])

    def _capture_submodule(self, key: str, source: Path, modules: Path, entry: dict, dest: Path) -> None:
        """Own bundle + index of one submodule gitdir. The source gitdir is only given a ref."""
        gd = modules / entry['name']
        dest.mkdir(parents=True, mode=0o700)
        refs = ['HEAD', '--branches', '--tags', '--remotes']
        if entry['populated']:
            # Blobs referenced only by the submodule's staged index.
            stash = _stash_create(source / entry['path'])
            if stash:
                ref = f'refs/runner-checkpoints/{key}'
                _gitdir(gd, 'update-ref', ref, stash)
                refs.append(ref)
        _gitdir(gd, 'bundle', 'create', str(dest / 'commits.bundle'), *refs)
        (dest / 'commits.bundle').chmod(0o600)
        if (gd / 'index').is_file():
            shutil.copy2(gd / 'index', dest / 'index')
            (dest / 'index').chmod(0o600)

    def read(self, checkpoint: Path) -> dict:
        with _IO_LOCK:      # a compaction holds this lock across its two renames
            retired = checkpoint.parent / f'.retired-{checkpoint.name}'
            if not os.path.lexists(checkpoint) and retired.is_dir():
                os.rename(retired, checkpoint)       # crash between the swap's two renames
        try:
            data = json.loads((checkpoint / 'manifest.json').read_text())
            if data['version'] not in (1, 2, 3):
                raise ValueError()
            for entry in data.get('submodules', []):
                if not (_safe_rel(entry['path']) and _safe_rel(entry['name'])
                        and isinstance(entry['populated'], bool) and isinstance(entry['gitdir'], bool)):
                    raise ValueError()
            # No names supplied by a manifest may escape the tree; a `.git` component is only
            # legitimate beneath a nested repository's root, which itself has none.
            tree = data['fingerprint']['tree']
            roots = set(nested_repos(tree))
            if any(not _safe_rel(r) for r in roots):
                raise ValueError()
            delta = data.get('delta') or {}
            names = [*tree, *delta.get('files', []), *delta.get('dirs', []), *delta.get('deleted', [])]
            if not all(_valid_tree_name(n, roots) for n in names):
                raise ValueError()
            for key in ('excludes', 'ignored'):
                if not isinstance(data.get(key, []), list):
                    raise ValueError()
                for name in data.get(key, []):
                    p = Path(name)
                    if not isinstance(name, str) or p.is_absolute() or '..' in p.parts or '.git' in p.parts:
                        raise ValueError()
            if not isinstance(data.get('objects', ''), str):
                raise ValueError()
            return data
        except (OSError, ValueError, KeyError, TypeError):
            raise WorkspaceError('checkpoint: invalid manifest') from None

    def _prove_bundle(self, bundle: Path, refspecs: list, message: str, reference: Path | None = None,
                      whole_pack: bool = False) -> None:
        """`bundle verify` checks only the header; unpack into scratch storage to prove the pack.

        A fetch skips the pack when the probe already reaches every tip, as it does through an alternate
        to the capture source's own store. `whole_pack` indexes the pack itself first (checksum, every
        object, fsck), so a pack that does not index is refused there too."""
        with tempfile.TemporaryDirectory(prefix='.preflight-', dir=self.root) as scratch:
            probe = Path(scratch) / 'probe'
            # No template: the sample hooks are a dozen files written and removed for nothing.
            ok = _run(['git', 'init', '--bare', '--quiet', '--template=', str(probe)],
                      capture_output=True).returncode == 0
            if ok and reference is not None:
                _alternate(probe / 'objects', reference)      # the bundle's prerequisite lives there
            if ok and whole_pack:
                # A bundle that cannot be read (gone, unreadable) is refused like a broken one: the
                # caller's fallback handles a refusal, not an OSError.
                try:
                    with open(bundle, 'rb') as header:      # signature, refs, a blank line, the pack
                        line = header.readline()
                        if line not in (b'# v2 git bundle\n', b'# v3 git bundle\n'):
                            raise WorkspaceError('checkpoint: ' + message)
                        while line not in (b'\n', b''):
                            line = header.readline()
                        if line != b'\n':
                            raise WorkspaceError('checkpoint: ' + message)
                        offset = header.tell()
                    # Unbuffered, so the child reads from `offset` (a buffered reader has read ahead of it).
                    with open(bundle, 'rb', buffering=0) as pack:
                        pack.seek(offset)
                        indexed = _run(['git', '--git-dir', str(probe), 'index-pack', '--stdin', '--fix-thin',
                                        '--strict'], stdin=pack, capture_output=True).returncode == 0
                except OSError:
                    raise WorkspaceError('checkpoint: ' + message) from None
                if not indexed:
                    raise WorkspaceError('checkpoint: ' + message)
            ok = ok and _run(
                # unpackLimit=1: keep the pack whole (a few files), never one loose file per object.
                ['git', '--git-dir', str(probe), '-c', 'transfer.fsckObjects=true', '-c', 'fetch.unpackLimit=1',
                 'fetch', '--quiet', str(bundle), *refspecs], capture_output=True).returncode == 0
            if not ok:
                raise WorkspaceError('checkpoint: ' + message)

    def _replay(self, checkpoint: Path, target: Path, prove: bool = True, *,
                completed: bool = False, marker: Path | None = None) -> None:
        data = self.read(checkpoint)
        # Validate stored tree before touching the destination (no link-following extraction).
        subs = data.get('submodules', [])
        excludes = tuple(data.get('excludes', []))
        ignored = tuple(data.get('ignored', []))
        delta = data.get('delta')
        expected = _delta_keep(data['fingerprint']['tree'], delta) if delta else data['fingerprint']['tree']
        _mark('verify-snapshot')
        if inventory(checkpoint / 'tree', tuple(e['path'] for e in subs if e['populated'])) != expected:
            raise WorkspaceError('checkpoint: snapshot hash mismatch')
        modules = _modules_dir(target)
        stale = self._check_target_submodules(checkpoint, target, data, completed=completed)
        # Parent target: no active writer. A retry after a partial replay must still be able to overwrite.
        gitdir = Path(git(target, 'rev-parse', '--absolute-git-dir'))
        if any(os.path.lexists(gitdir / lock) for lock in ('index.lock', 'HEAD.lock')):
            raise RestoreRefused('checkpoint: active git writer in target; lease retained')
        # Preflight every stored component before the target is touched.
        for i, entry in enumerate(subs):
            if not entry['gitdir']:
                continue
            part = checkpoint / 'submodules' / str(i)
            if not (part / 'commits.bundle').is_file() or (entry['populated'] and not (part / 'index').is_file()):
                raise WorkspaceError('checkpoint: submodule snapshot incomplete')
            self._prove_bundle(part / 'commits.bundle', ['+refs/heads/*:refs/heads/*', '+refs/tags/*:refs/tags/*',
                                                         '+refs/remotes/*:refs/remotes/*', '+HEAD:refs/runner-replay/HEAD'],
                               'submodule bundle invalid; target untouched')
        bundle = data.get('bundle')
        _mark('verify-base')
        if bundle:
            self._ensure_base(checkpoint, target, bundle['base'], data['source'])
        refspecs = ['+refs/*:refs/runner-replay/*', *(['HEAD'] if not bundle or bundle['has_head'] else [])]
        if bundle and bundle['mode'] == 'none':
            if _run(['git', '-C', str(target), 'cat-file', '-e', f"{data['fingerprint']['head']}^{{commit}}"],
                              capture_output=True).returncode:
                raise WorkspaceError('checkpoint: base commit missing in target; target untouched')
        elif prove:
            self._prove_bundle(checkpoint / 'commits.bundle', refspecs, 'bundle invalid; target untouched',
                               reference=_objects_dir(target) if bundle else None)
        if marker is not None:
            # Mark replay in progress only after all preflight checks pass, using `'replaying'`
            # (never `'checkpoint'`) so an older runner cannot treat an interrupted replay as done.
            atomic_json(marker, {'replaying': checkpoint.name, 'result': self._result_digest(data)})
        if modules.parent.is_dir():
            for leftover in modules.parent.glob('.runner-replay-gd-*'):
                if leftover.is_dir() and not leftover.is_symlink():
                    _rmtree(leftover, ignore_errors=True)
        self._set_aside_stale_submodules(target, stale)
        _mark('verify-fetch')
        # Replay never needs the target's own submodules; a set-aside gitdir would break the recursion.
        if not (bundle and bundle['mode'] == 'none'):
            git(target, 'fetch', '--quiet', '--no-recurse-submodules', str(checkpoint / 'commits.bundle'), *refspecs)
        branch = data.get('branch')
        _mark('verify-checkout')
        if isinstance(branch, str) and branch.startswith('refs/heads/'):
            git(target, 'checkout', '--quiet', '--force', '-B', branch[len('refs/heads/'):], data['fingerprint']['head'])
        else:
            git(target, 'checkout', '--quiet', '--force', '--detach', data['fingerprint']['head'])
        _mark('verify-overlay')
        _clear_tree(target)
        roots = tuple(e['path'] for e in subs if e['populated'])
        inner = {}
        if delta:
            # A populated submodule's part goes in after its own HEAD is checked out (`_replay_submodule`).
            outer, inner = _split_delta(delta, roots)
            self._overlay_delta(checkpoint / 'tree', target, data['fingerprint']['tree'], outer, roots=roots)
        else:
            for child in (checkpoint / 'tree').iterdir():
                dest = target / child.name
                if child.is_symlink():
                    os.symlink(os.readlink(child), dest)
                elif child.is_dir():
                    _copy(child, dest)
                else:
                    shutil.copy2(child, dest)
        _mark('verify-index')
        index = Path(git(target, 'rev-parse', '--git-path', 'index'))
        if not index.is_absolute():
            index = target / index
        # A crash during copy must never leave a truncated authoritative index;
        # git itself uses atomic lock/rename for subsequent stat refreshes.
        index_tmp = index.with_name('runner-checkpoint-index.tmp')
        shutil.copy2(checkpoint / 'index', index_tmp)
        _sync(index_tmp)
        os.replace(index_tmp, index)
        _sync(index.parent)
        for i, entry in enumerate(subs):
            if entry['gitdir']:
                self._replay_submodule(checkpoint / 'submodules' / str(i), target, modules, entry, data,
                                       inner.get(entry['path']), checkpoint / 'tree')
        _mark('verify-refresh')
        git(target, 'update-index', '--really-refresh', check=False)
        for entry in subs:
            if entry['populated']:
                git(target / entry['path'], 'update-index', '--really-refresh', check=False)
        _mark('verify-fingerprint')
        if fingerprint(target, subs, excludes, ignored) != data['fingerprint']:
            raise WorkspaceError('checkpoint: replay verification failed; lease retained')

    @staticmethod
    def _ensure_base(checkpoint: Path, target: Path, base: str, source: str) -> None:
        """A slim bundle needs its base commit in the target. Pool slots share the base clone's objects;
        any other target gets it from the capture source, where a checkpoint ref pins it."""
        def have():
            return _run(['git', '-C', str(target), 'cat-file', '-e', f'{base}^{{commit}}'],
                                  capture_output=True).returncode == 0
        if have():
            return
        ref = f'refs/runner-checkpoint-bases/{checkpoint.name}'
        _run(['git', '-C', str(target), 'fetch', '--quiet', '--no-recurse-submodules', source, ref],
                       capture_output=True)       # objects only: no ref is written into the target
        if not have():
            raise WorkspaceError('checkpoint: base commit missing in target; target untouched')

    @staticmethod
    def _overlay_delta(tree: Path, target: Path, full: dict, delta: dict, roots: tuple = ()) -> None:
        """HEAD's files from the object store (already fetched), then the delta over them. `roots`: the
        populated submodules, empty directories here (their gitlinks); their content comes later."""
        git(target, 'checkout-index', '--all', '--force')
        Checkpoints._apply_delta(tree, target, full, delta,
                                 lambda n: not any(n.startswith(r + '/') for r in roots))

    @staticmethod
    def _apply_delta(tree: Path, target: Path, full: dict, delta: dict, mine,
                     root_override: tuple[str, Path] | None = None) -> None:
        """The delta over a checkout already in `target`; then the recorded modes of the entries `mine`
        selects (the checkout's repository: the superproject, or one populated submodule).

        When `root_override` is `(prefix, stage_dir)`, every path starting with `prefix` is written
        beneath `stage_dir` instead of `target / prefix` (atomic submodule worktree assembly)."""
        if root_override is not None:
            pre, dest_root = root_override
        else:
            pre, dest_root = '', target
        root = os.path.realpath(dest_root)

        def dest_path(name: str) -> Path:
            if pre:
                if not name.startswith(pre):
                    raise WorkspaceError(f'checkpoint: delta path outside the restore root: {name}')
                return dest_root / name[len(pre):]
            return dest_root / name

        def inside(name: str) -> Path:
            # Defence in depth behind `read()`: whatever is written or removed lies under the restore root
            # (the last component may itself be a link, which is acted on, never followed).
            p = dest_path(name)
            parent = os.path.realpath(p.parent)
            if parent != root and not parent.startswith(root + os.sep):
                raise WorkspaceError(f'checkpoint: delta path outside the restore root: {name}')
            return p
        for name in delta['deleted']:
            p = inside(name)
            if os.path.lexists(p) and not p.is_dir():
                p.unlink()
        for name in sorted(delta['files']):
            src, out = tree / name, inside(name)
            out.parent.mkdir(parents=True, exist_ok=True)
            if os.path.lexists(out):
                if out.is_dir() and not out.is_symlink():
                    _rmtree(out)
                else:
                    out.unlink()
            if src.is_symlink():
                os.symlink(os.readlink(src), out)
            else:
                shutil.copy2(src, out)
        for name in delta['dirs']:
            inside(name).mkdir(parents=True, exist_ok=True)
        # Checkout creates files with this process's umask; the source had its own. Put the recorded
        # modes back (files first, directories deepest-first so a read-only parent is closed last).
        for kind in ('file', 'link', 'dir'):
            for name in sorted((n for n, v in full.items() if v[0] == kind and mine(n)),
                               key=lambda n: (-len(Path(n).parts), n)):
                p = dest_path(name)
                if not os.path.lexists(p) or stat.S_IMODE(p.lstat().st_mode) == full[name][1]:
                    continue
                try:
                    os.chmod(p, full[name][1], follow_symlinks=False)
                except NotImplementedError:     # no lchmod on this platform: a link's mode is not enforced there
                    pass

    def _check_target_submodules(self, checkpoint: Path, target: Path, data: dict,
                                 *, completed: bool = False) -> list:
        """Validate the submodule gitdirs already present in the target.

        A gitdir equal to the checkpointed one is kept (and must hold the same work, or a provably
        partial replay of this checkpoint when no completed restore marker exists). One that
        differs is a leftover of an earlier lease of this pooled slot: it is returned for
        `_set_aside_stale_submodules` when it provably holds nothing the remote lacks, otherwise
        the restore is refused. Nothing is changed here."""
        modules = _modules_dir(target)
        stale = []
        for entry in data.get('submodules', []):
            gd = modules / entry['name']
            if os.path.lexists(gd):
                if any(c.is_symlink() for c in (modules, *[gd.parents[k] for k in range(len(Path(entry['name']).parts) - 1)], gd)):
                    raise RestoreRefused(f"checkpoint: symlinked submodule gitdir in target unsupported: {entry['path']}")
                have = _submodule_state(target, {**entry, 'populated': False}, modules)
                want = data['fingerprint']['submodules'][entry['path']]
                if any(have.get(k) != want.get(k) for k in ('gitdir', 'head', 'branch', 'refs')):
                    if any(os.path.lexists(gd / lock) for lock in ('index.lock', 'HEAD.lock')):
                        raise RestoreRefused(f"checkpoint: active git writer in target submodule {entry['path']}; lease retained")
                    part = checkpoint / 'submodules' / str(data['submodules'].index(entry)) / 'commits.bundle'
                    why = _stale_submodule_work(target, entry, gd,
                                                _bundle_tags(part) if entry.get('gitdir') and part.is_file() else None)
                    if why:
                        # this card's target slot, not the lane: the start path holds this card only
                        raise RestoreRefused(f"checkpoint: submodule gitdir differs in target ({why}): {entry['path']}; lease retained")
                    stale.append(entry)
                    continue
                if any(os.path.lexists(gd / lock) for lock in ('index.lock', 'HEAD.lock')):
                    raise RestoreRefused(f"checkpoint: active git writer in target submodule {entry['path']}; lease retained")
                self._require_same_submodule_work(checkpoint, target, entry, data, gd, completed=completed)
        return stale

    def _set_aside_stale_submodules(self, target: Path, stale: list) -> None:
        """Move each stale gitdir next to (not inside) the modules directory, and its worktree
        into `.runner-stale-submodules-<slot>` beside the real slot directory.

        Each half stays on its own volume: a pooled slot may live on another volume than the
        git directory it shares with the base clone, and a rename never crosses volumes. So
        both moves are atomic renames and nothing is copied or deleted. The worktree goes
        whole, so tracked, untracked and ignored files all survive; replay then clears and
        fills an empty path. A move that still fails puts the worktree back and refuses this
        card's restore (`RestoreRefused`) with the lease retained. The parked pair stays
        usable: the worktree `.git` pointer and the gitdir `core.worktree` are rewritten to
        the new locations (a standalone clone needs neither). The runner never purges a
        parked pair."""
        modules = _modules_dir(target)
        todo = []
        for entry in stale:
            gd, wt = modules / entry['name'], target / entry['path']
            has_wt = wt.is_dir() and not wt.is_symlink() and any(wt.iterdir())
            if os.path.lexists(gd) or has_wt:       # else a crashed earlier replay already moved both
                todo.append((entry, gd, wt, has_wt))
        if not todo:
            return
        park = self._set_aside_dir(modules.parent / 'runner-stale-submodules')
        real = Path(os.path.realpath(target))       # the slot's own volume, never through a pool link
        wt_park = (self._set_aside_dir(real.parent / f'.runner-stale-submodules-{real.name}')
                   if any(has_wt for *_, has_wt in todo) else None)
        stamp = datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S')
        for entry, gd, wt, has_wt in todo:
            label = entry['name'].replace('/', '__')
            n = 0
            while True:
                name = f'{stamp}-{label}' + (f'-{n}' if n else '')
                dest = park / name
                moved_wt = wt_park / f'{name}.worktree' if has_wt else None
                if not os.path.lexists(dest) and not (moved_wt and os.path.lexists(moved_wt)):
                    break
                n += 1
            try:
                if has_wt:
                    os.rename(wt, moved_wt)
                if os.path.lexists(gd):
                    os.rename(gd, dest)
            except OSError as e:
                if has_wt and os.path.lexists(moved_wt) and not os.path.lexists(wt):
                    os.rename(moved_wt, wt)         # put the worktree back; nothing was lost
                raise RestoreRefused(f"checkpoint: cannot set aside stale submodule {entry['path']} "
                                     f"({e.strerror}); lease retained") from None
            if has_wt and os.path.lexists(dest):
                self._reconnect_parked(dest, moved_wt)
            for parent in gd.parents:       # prune now-empty intermediate directories, never above modules
                if parent == modules.parent:
                    break
                try:
                    parent.rmdir()
                except OSError:
                    break
            _sync(park)
            if has_wt:
                _sync(wt_park)

    @staticmethod
    def _set_aside_dir(park: Path) -> Path:
        """`park`, created private when missing; a symlink, a non-directory or a directory of
        another user there refuses this card's restore."""
        try:
            info = os.lstat(park)
        except FileNotFoundError:
            try:
                os.mkdir(park, 0o700)           # mkdir never follows a symlink at the last component
            except OSError as e:
                raise RestoreRefused(f'checkpoint: cannot create the set-aside directory ({e.strerror}); '
                                     'lease retained') from None
        else:
            if not stat.S_ISDIR(info.st_mode) or info.st_uid != os.getuid():
                raise RestoreRefused('checkpoint: set-aside path is a symlink, not a directory or not ours; '
                                     'lease retained')
        return park

    @staticmethod
    def _reconnect_parked(gd: Path, wt: Path) -> None:
        """Best effort: point the parked worktree and gitdir at each other again."""
        pointer = wt / '.git'
        if pointer.is_file() and not pointer.is_symlink():
            tmp = pointer.with_name('.git.runner-tmp')
            tmp.write_text('gitdir: ' + os.path.relpath(os.path.realpath(gd), os.path.realpath(wt)) + '\n')
            os.replace(tmp, pointer)
        if _gitdir(gd, 'config', '--get', 'core.worktree', check=False):
            _gitdir(gd, 'config', 'core.worktree', os.path.relpath(os.path.realpath(wt), os.path.realpath(gd)), check=False)

    def _require_same_submodule_work(self, checkpoint: Path, target: Path, entry: dict, data: dict, gd: Path,
                                     *, completed: bool = False) -> None:
        """An existing target submodule may hold newer work; never replace anything that differs.

        When no completed restore marker exists for this checkpoint, a worktree that provably holds
        only a partial replay of this checkpoint (missing files, un-restored modes, truncated copies,
        or pre-delta HEAD blobs, with zero foreign files or index changes) may be retried."""
        i = data['submodules'].index(entry)
        saved = checkpoint / 'submodules' / str(i) / 'index'
        current = gd / 'index'
        wt = target / entry['path']
        present = wt.is_dir() and not wt.is_symlink() and any(wt.iterdir())
        # Stat refreshes rewrite index bytes without changing the staged content.
        if current.is_file() and (not saved.is_file() or _submodule_index(gd, current) != _submodule_index(gd, saved)):
            raise RestoreRefused(f"checkpoint: submodule work in target differs from checkpoint: {entry['path']}; lease retained")
        if present:
            have = _submodule_state(target, entry, _modules_dir(target))
            want = data['fingerprint']['submodules'][entry['path']]
            prefix = entry['path'] + '/'
            roots = tuple(e['path'] for e in data['submodules'] if e['populated'])
            skip = frozenset((*data.get('excludes', []), *data.get('ignored', [])))
            now = {k: v for k, v in inventory(target, roots, skip).items() if k.startswith(prefix)}
            want_tree = {k: v for k, v in data['fingerprint']['tree'].items() if k.startswith(prefix)}
            if have != want or now != want_tree:
                if completed or not self._is_partial_submodule_replay(
                        checkpoint, target, entry, data, gd, now, want_tree):
                    raise RestoreRefused(
                        f"checkpoint: submodule work in target differs from checkpoint: {entry['path']}; lease retained")

    @staticmethod
    def _is_partial_submodule_replay(checkpoint: Path, target: Path, entry: dict, data: dict,
                                     gd: Path, now: dict, want_tree: dict) -> bool:
        """True only when every entry present in `wt` is consistent with an interrupted replay of
        this checkpoint (no foreign files, no user edits, valid `.git` pointer if present)."""
        wt = target / entry['path']
        pointer = wt / '.git'
        if os.path.lexists(pointer):
            if pointer.is_symlink() or not pointer.is_file():
                return False
            text = pointer.read_text(errors='surrogateescape')
            if (not text.startswith('gitdir: ') or '\n' in text.strip()
                    or os.path.realpath(wt / text[len('gitdir: '):].strip()) != os.path.realpath(gd)):
                return False
        prefix = entry['path'] + '/'
        delta = data.get('delta')
        if isinstance(delta, dict):
            delta_files = {n for n in delta.get('files', []) if n.startswith(prefix)}
            delta_deleted = {n for n in delta.get('deleted', []) if n.startswith(prefix)}
        else:
            delta_files, delta_deleted = set(), set()
        deleted_parents = {p for n in delta_deleted for p in _parents(n)}
        head_cache: dict[str, tuple[str, bytes] | None] = {}

        def head_entry(rel: str):
            if rel not in head_cache:
                r = _run(['git', '--git-dir', str(gd), 'ls-tree', '-z', 'HEAD', '--', rel], capture_output=True)
                if r.returncode or not r.stdout:
                    head_cache[rel] = None
                else:
                    record = r.stdout.split(b'\0')[0]
                    meta, _, _ = record.partition(b'\t')
                    mode, kind, oid = meta.decode('ascii').split()
                    if kind != 'blob':
                        head_cache[rel] = None
                    else:
                        b = _run(['git', '--git-dir', str(gd), 'cat-file', 'blob', oid], capture_output=True)
                        head_cache[rel] = (mode, b.stdout) if b.returncode == 0 else None
            return head_cache[rel]

        def matches_head(name: str, entry_val: list) -> bool:
            he = head_entry(name[len(prefix):])
            if he is None:
                return False
            h_mode, h_bytes = he
            if h_mode == '120000':
                return entry_val[0] == 'link' and os.fsencode(entry_val[2]) == h_bytes
            if h_mode in ('100644', '100755'):
                return (entry_val[0] == 'file' and entry_val[2] == len(h_bytes)
                        and entry_val[3] == hashlib.sha256(h_bytes).hexdigest())
            return False

        def is_prefix_of_source(name: str, disk_size: int) -> bool:
            if disk_size == 0:
                return True
            src_file = checkpoint / 'tree' / name
            try:
                if src_file.is_file() and not src_file.is_symlink():
                    with src_file.open('rb') as f:
                        want_prefix = f.read(disk_size)
                    with (target / name).open('rb') as f:
                        have_bytes = f.read(disk_size + 1)
                    return len(have_bytes) == disk_size and have_bytes == want_prefix
                he = head_entry(name[len(prefix):])
                if he is not None and he[0] in ('100644', '100755') and len(he[1]) > disk_size:
                    with (target / name).open('rb') as f:
                        have_bytes = f.read(disk_size + 1)
                    return len(have_bytes) == disk_size and have_bytes == he[1][:disk_size]
            except OSError:
                return False
            return False

        for k, v in now.items():
            if k == prefix + '.git.runner-tmp':
                if v[0] == 'file' and v[2] <= 4096:
                    continue
                return False
            w = want_tree.get(k)
            if w is None:
                if v[0] == 'dir' and k in deleted_parents:
                    continue
                if k in delta_deleted and matches_head(k, v):
                    continue
                return False
            if v == w:
                continue
            if v[0] == w[0] == 'dir' and v[2:] == w[2:]:
                continue
            if v[0] == w[0] == 'link' and v[2] == w[2]:
                continue
            if v[0] == w[0] == 'file':
                if v[2] == w[2] and v[3] == w[3]:
                    continue
                if v[2] < w[2] and is_prefix_of_source(k, v[2]):
                    continue
            if k in delta_files and matches_head(k, v):
                continue
            return False
        return True

    def _replay_submodule(self, src: Path, target: Path, modules: Path, entry: dict, data: dict,
                          delta: dict | None = None, tree: Path | None = None) -> None:
        """The submodule's gitdir from its bundle and index; a populated one gets its pointer back and, in
        the slim form (`delta`: its part), its worktree: HEAD checked out, then that part over it.

        New gitdirs and slim worktrees are assembled in sibling staging directories and renamed into
        place atomically so an interruption mid-replay leaves no half-populated submodule tree."""
        gd = modules / entry['name']
        wt = target / entry['path']
        want = data['fingerprint']['submodules'][entry['path']]
        if not os.path.lexists(gd):
            gd.parent.mkdir(parents=True, exist_ok=True)
            gd_stage = Path(tempfile.mkdtemp(prefix='.runner-replay-gd-', dir=modules.parent))
            try:
                _run(['git', 'init', '--bare', '--quiet', str(gd_stage)], check=True, capture_output=True)
                _gitdir(gd_stage, 'fetch', '--quiet', str(src / 'commits.bundle'),
                        '+refs/heads/*:refs/heads/*', '+refs/tags/*:refs/tags/*',
                        '+refs/remotes/*:refs/remotes/*', '+refs/runner-checkpoints/*:refs/runner-checkpoints/*',
                        '+HEAD:refs/runner-replay/HEAD')
                if want['branch']:
                    _gitdir(gd_stage, 'symbolic-ref', 'HEAD', want['branch'])
                else:
                    _gitdir(gd_stage, 'update-ref', '--no-deref', 'HEAD', want['head'])
                _gitdir(gd_stage, 'update-ref', '-d', 'refs/runner-replay/HEAD')
                # Record the replayed refs the way a clone does (packed-refs): a fetch from the bundle
                # leaves every tag loose, and a later restore into this slot would take the runner's
                # own replay for someone's tags and refuse it.
                _gitdir(gd_stage, 'pack-refs', '--all')
                _gitdir(gd_stage, 'config', 'core.bare', 'false')
                final_gd = Path(os.path.realpath(gd.parent)) / gd.name
                _gitdir(gd_stage, 'config', 'core.worktree',
                        os.path.relpath(os.path.realpath(wt), str(final_gd)))
                if (src / 'index').is_file():
                    shutil.copy2(src / 'index', gd_stage / 'index')
                    _sync(gd_stage / 'index')
                _sync(gd_stage)
                os.rename(gd_stage, gd)
                _sync(gd.parent)
            except BaseException:
                _rmtree(gd_stage, ignore_errors=True)
                raise
        else:
            if any(os.path.lexists(gd / lock) for lock in ('index.lock', 'HEAD.lock')):
                raise RestoreRefused(f"checkpoint: active git writer in target submodule {entry['path']}; lease retained")
            if (src / 'index').is_file():
                tmp = gd / 'runner-checkpoint-index.tmp'
                shutil.copy2(src / 'index', tmp)
                _sync(tmp)
                os.replace(tmp, gd / 'index')
                _sync(gd)
        if entry['populated']:
            if delta is not None:
                parent = wt.parent
                parent_mode = stat.S_IMODE(parent.lstat().st_mode)
                if parent_mode & 0o700 != 0o700:
                    os.chmod(parent, parent_mode | 0o700)
                wt_stage = Path(tempfile.mkdtemp(prefix='.runner-replay-wt-', dir=parent))
                try:
                    pointer = wt_stage / '.git'
                    pointer.write_text('gitdir: ' + os.path.relpath(os.path.realpath(gd), os.path.realpath(wt)) + '\n')
                    self._checkout_submodule_head(gd, wt_stage)
                    prefix = entry['path'] + '/'
                    self._apply_delta(tree, target, data['fingerprint']['tree'], delta,
                                      lambda n: n.startswith(prefix), root_override=(prefix, wt_stage))
                    wt_mode = data['fingerprint']['tree'].get(entry['path'], [None, None])[1]
                    _sync(wt_stage)
                    if os.path.lexists(wt) and wt.is_dir() and not wt.is_symlink():
                        wt_cur_mode = stat.S_IMODE(wt.lstat().st_mode)
                        if wt_cur_mode & 0o700 != 0o700:
                            os.chmod(wt, wt_cur_mode | 0o700)
                    os.replace(wt_stage, wt)
                    if wt_mode is not None:
                        os.chmod(wt, wt_mode)
                    _sync(parent)
                except BaseException:
                    _rmtree(wt_stage, ignore_errors=True)
                    raise
                finally:
                    if parent_mode & 0o700 != 0o700:
                        os.chmod(parent, parent_mode)
            else:
                pointer = wt / '.git'
                if pointer.is_symlink():
                    raise RestoreRefused(f"checkpoint: unsafe submodule pointer: {entry['path']}")
                tmp = pointer.with_name('.git.runner-tmp')
                tmp.write_text('gitdir: ' + os.path.relpath(os.path.realpath(gd), os.path.realpath(pointer.parent)) + '\n')
                os.replace(tmp, pointer)

    @staticmethod
    def _checkout_submodule_head(gd: Path, wt: Path) -> None:
        """Write the files of the submodule's HEAD into `wt` (empty: the superproject's checkout made it),
        through a scratch index, so its own index is not read or written."""
        scratch = gd / 'runner-checkout-index.tmp'
        env = dict(os.environ, GIT_INDEX_FILE=str(scratch))
        env.pop('GIT_DIR', None)
        env.pop('GIT_WORK_TREE', None)
        try:
            for args in (('read-tree', 'HEAD'), ('checkout-index', '--all', '--force')):
                r = _run(['git', '--git-dir', str(gd), '--work-tree', str(wt), *args], capture_output=True,
                         text=True, errors='surrogateescape', env=env)
                if r.returncode:
                    raise WorkspaceError(f'checkpoint: git {args[0]} failed in a submodule gitdir: '
                                         f'{r.stderr.strip()[:120]}')
        finally:
            scratch.unlink(missing_ok=True)

    def _prove_in_place(self, checkpoint: Path, data: dict) -> None:
        """Prove a slim snapshot without laying its tree out anywhere.

        The scratch replay checked the whole tree out, applied the delta and compared the fingerprint:
        every capture wrote and removed the full checkout (tens of thousands of files) in the checkpoint
        directory. Here the same result is predicted from what the replay is made of and compared with
        the recorded fingerprint: the tree from HEAD's tree and blobs in the durable object store (the
        capture source's own store) and the delta tree as stored; Git's view (head, staged, unstaged,
        status) from a repository made the way the replay makes one, over the capture source. Every
        Git read runs in that repository, so config and attributes are the replay's, not the source's.
        Raises `_NotProvable` for anything it does not model exactly (a full snapshot, submodules,
        config it does not model, a path Git resolves against the work tree, checkout conversions, a
        changed `.gitattributes`, a deleted symlink, a tracked path under an ignored one, a layout the
        replay would refuse) and for every mismatch: the caller then runs the scratch replay, which
        stays the authority. Accepting here implies the replay accepts.

        Capture only: the capture source must still hold the tree just recorded (its writer is stopped,
        and the capture re-fingerprints it afterwards). The bundle is proven by the caller."""
        _mark('verify-proof')
        try:
            self._predict_replay(checkpoint, data)
        except _NotProvable:
            raise
        except (WorkspaceError, OSError, ValueError, KeyError, TypeError, AttributeError) as e:
            raise _NotProvable(f'error-{type(e).__name__}') from None

    def _predict_replay(self, checkpoint: Path, data: dict) -> None:
        delta, bundle = data.get('delta'), data.get('bundle')
        if not isinstance(delta, dict) or not isinstance(bundle, dict):
            raise _NotProvable('form')
        source = Path(data['source'])
        objects = _durable_objects(data)
        here = base_objects_dir(source) if source.is_dir() else None
        if objects is None or here is None or os.path.realpath(here) != os.path.realpath(objects):
            raise _NotProvable('objects')
        full = data['fingerprint']['tree']
        skip = {*data.get('excludes', []), *data.get('ignored', [])}
        # The `.gitattributes` files of the work tree are the source's; the replay's are HEAD's. They
        # agree unless one is among the changed, deleted, ignored or excluded paths.
        if any(n.rsplit('/', 1)[-1] == '.gitattributes' for n in (*delta['files'], *delta['deleted'], *skip)):
            raise _NotProvable('attributes')
        roots = tuple(e['path'] for e in data.get('submodules') or [] if e['populated'])
        if inventory(checkpoint / 'tree', roots) != _delta_keep(full, delta):
            raise _NotProvable('snapshot')
        with self._replay_repo(checkpoint, data, source, objects) as env:
            self._predict_in(data, source, env, checkpoint)

    @contextlib.contextmanager
    def _replay_repo(self, checkpoint: Path, data: dict, source: Path, objects: Path):
        """The environment of a Git command in a repository made as the replay makes its target, with the
        capture source as its work tree. `git init` as the replay runs it: the replay's config, template
        and `info/attributes`, not the source's (its local config, `info/attributes`, `attr.tree`,
        replace refs); the stored index; HEAD at the recorded commit; objects through the durable store.
        Nothing is written in the source.

        Without `GIT_CONFIG`: it redirects only the `git config` command (to that one file, includes not
        followed), while checkout, diff and status read the user-wide, system and repository config. With
        it the proof's config read would see a file no replay command reads, and could miss a key that
        steers the replay's checkout (`core.symlinks=false` in the user-wide config behind an empty
        `GIT_CONFIG`). Without it `git config` reads what every replay command reads."""
        with tempfile.TemporaryDirectory(prefix='.preflight-', dir=self.root) as scratch:
            view = Path(scratch) / 'view'
            view.mkdir()
            if _run(['git', '-C', str(view), 'init', '--quiet'], capture_output=True).returncode:
                raise _NotProvable('git-init')
            gitdir = view / '.git'
            _alternate(gitdir / 'objects', objects)
            (gitdir / 'HEAD').write_text(data['fingerprint']['head'] + '\n')
            shutil.copyfile(checkpoint / 'index', gitdir / 'index')
            env = {k: v for k, v in os.environ.items() if k != 'GIT_CONFIG'}
            yield dict(env, GIT_DIR=str(gitdir), GIT_WORK_TREE=str(source), **_READ_ONLY_GIT)

    def _replay_submodules(self, checkpoint: Path | None, data: dict, source: Path, env: dict, check_hooks) -> dict:
        """Each submodule as the replay restores it into a fresh target (`_replay_submodule`), next to the
        proof's repository: `git init --bare`, its bundle fetched (proven: fsck, the whole pack kept), HEAD,
        the stored index. Its recorded state must come out: HEAD, branch and refs; for a populated one
        its staged, unstaged and status, read with the source's submodule worktree as the work tree (the
        tree proof shows the replay's holds the same files). Returns {path: environment} of the populated
        ones, for their HEAD trees and blobs. A submodule without a gitdir stays without one.

        The superproject's own view looks into a populated submodule through the source's pointer, so
        through the source's gitdir: `_same_submodule_view` requires that gitdir to read like the
        replay's (config, `info/` files); the content, HEAD and index are what is proven here."""
        if checkpoint is None:
            raise _NotProvable('form')
        base = {k: v for k, v in env.items() if k not in ('GIT_DIR', 'GIT_WORK_TREE', 'GIT_INDEX_FILE')}
        modules = Path(env['GIT_DIR']) / 'modules'
        source_modules = _modules_dir(source)
        recorded = data['fingerprint'].get('submodules') or {}
        template = [] if not self._template_inert(Path(env['GIT_DIR'])) else ['--template=']
        out = {}
        for i, entry in enumerate(data['submodules']):
            want = recorded.get(entry['path'])
            if not entry['gitdir']:
                if want != {'gitdir': False}:
                    raise _NotProvable('submodule-state')
                continue
            part = checkpoint / 'submodules' / str(i)
            if not isinstance(want, dict) or not (part / 'commits.bundle').is_file() or (
                    entry['populated'] and not (part / 'index').is_file()):
                raise _NotProvable('submodule-snapshot')
            gd = modules / entry['name']
            gd.parent.mkdir(parents=True, exist_ok=True)

            def run(what: str, *args, gd=gd):
                if _run(['git', '--git-dir', str(gd), *args], capture_output=True, env=base).returncode:
                    raise _NotProvable(f'submodule-{what}')
            if _run(['git', 'init', '--bare', '--quiet', *template, str(gd)], capture_output=True,
                    env=base).returncode:
                raise _NotProvable('submodule-init')
            # The bundle is proven here as the replay's preflight proves it: every object checked.
            run('bundle', '-c', 'transfer.fsckObjects=true', '-c', 'fetch.unpackLimit=1', 'fetch', '--quiet',
                '--no-write-fetch-head', str(part / 'commits.bundle'),
                '+refs/heads/*:refs/heads/*', '+refs/tags/*:refs/tags/*', '+refs/remotes/*:refs/remotes/*',
                '+refs/runner-checkpoints/*:refs/runner-checkpoints/*', '+HEAD:refs/runner-replay/HEAD')
            if want.get('branch'):
                run('head', 'symbolic-ref', 'HEAD', want['branch'])
            else:
                run('head', 'update-ref', '--no-deref', 'HEAD', want.get('head') or '')
            run('head', 'update-ref', '-d', 'refs/runner-replay/HEAD')
            run('config', 'config', 'core.bare', 'false')
            if (part / 'index').is_file():
                shutil.copyfile(part / 'index', gd / 'index')
            state = _gitdir_state(gd)
            if entry['populated']:
                wt = source / entry['path']
                where = dict(base, GIT_DIR=str(gd), GIT_WORK_TREE=str(wt))
                check_hooks(where, wt)
                self._same_submodule_view(source_modules / entry['name'], gd)
                # As the replay does before its fingerprint; writes this gitdir's index only.
                _run(['git', '-C', str(wt), 'update-index', '--really-refresh'], capture_output=True, env=where)

                def raw(*args, where=where, wt=wt):
                    r = _run(['git', '-C', str(wt), *args], capture_output=True, env=where)
                    if r.returncode:
                        raise _NotProvable(f'git-{args[0]}')
                    return hashlib.sha256(r.stdout).hexdigest()
                state.update(_worktree_state(raw))
                out[entry['path']] = where
            if state != want:
                raise _NotProvable('submodule-state')
        return out

    @staticmethod
    def _template_inert(view: Path) -> bool:
        """Whether the template `git init` copied into the proof's repository `view` (the replay's `git init`
        copies the same one into every submodule gitdir it makes) gives a gitdir nothing that its Git reads:
        only sample hooks, `description` and a comment-only `info/exclude`, and no config key beyond those
        `git init` writes itself. Then the proof makes its submodule gitdirs without a template: the same
        Git behaviour, sixteen files fewer per submodule. Anything else (a hook, an attributes file, a
        template config, another ref store): False, and they are made with the template, as the replay
        does. Read before the proof writes anything but `index` and the alternate there."""
        ours = {'HEAD', 'config', 'description', 'index', 'info/exclude', 'objects/info/alternates'}
        for parent, dirs, files in os.walk(view):
            for name in files:
                rel = (Path(parent) / name).relative_to(view).as_posix()
                if rel not in ours and not (rel.startswith('hooks/') and rel.count('/') == 1
                                            and rel.endswith('.sample')):
                    return False
        try:
            exclude = (view / 'info' / 'exclude').read_bytes() if (view / 'info' / 'exclude').exists() else b''
        except OSError:
            return False
        if any(ln.strip() and not ln.startswith(b'#') for ln in exclude.splitlines()):
            return False
        r = _run(['git', 'config', '--file', str(view / 'config'), '--list', '-z', '--name-only'],
                 capture_output=True)
        if r.returncode:
            return False
        return all(key in _INIT_CONFIG for key in r.stdout.decode('utf-8', 'surrogateescape').lower().split('\0')
                   if key)

    @staticmethod
    def _same_submodule_view(have: Path, made: Path) -> None:
        """The source's submodule gitdir `have` gives what the replay's `made` gives to the superproject's
        status and diff (which run Git in the submodule through the source's pointer): the same local
        config but for keys no such run reads, the same `info/exclude`, `info/attributes` and
        `info/sparse-checkout` (comment and blank lines aside, the rest byte for byte). Anything else hands
        over."""
        def config(gd: Path) -> list:
            r = _run(['git', 'config', '--file', str(gd / 'config'), '--list', '-z'], capture_output=True)
            if r.returncode:
                raise _NotProvable('submodule-config')
            keys = []
            for record in r.stdout.split(b'\0'):
                if not record:
                    continue
                name, given, value = record.partition(b'\n')
                key = name.decode('utf-8', 'surrogateescape').lower()
                if key.split('.', 1)[0] in _SUBMODULE_INERT_SECTIONS or key in _SUBMODULE_INERT_KEYS:
                    continue
                keys.append((key, value if given else None))
            return sorted(keys)

        def lines(path: Path) -> list:
            try:
                text = path.read_bytes()
            except FileNotFoundError:
                return []
            except OSError:
                raise _NotProvable('submodule-info') from None
            return [ln for ln in text.splitlines() if ln.strip() and not ln.startswith(b'#')]
        if config(have) != config(made):
            raise _NotProvable('submodule-config')
        if any(lines(have / name) != lines(made / name)
               for name in ('info/exclude', 'info/attributes', 'info/sparse-checkout')):
            raise _NotProvable('submodule-info')

    def _predict_in(self, data: dict, source: Path, env: dict, checkpoint: Path | None = None) -> None:
        """Predict the replay's result from inside its repository (`env`, from `_replay_repo`) and
        compare it with the fingerprint; `_NotProvable` names the first thing that is not decided.
        Submodules (their stored parts under `checkpoint`): see `_replay_submodules`."""
        delta, bundle = data['delta'], data['bundle']
        full = data['fingerprint']['tree']
        head = data['fingerprint']['head']
        skip = {*data.get('excludes', []), *data.get('ignored', [])}

        def run_in(where: dict, cwd: Path, *args, feed=None, ok=(0,)):
            r = _run(['git', '-C', str(cwd), *args], capture_output=True, env=where, input=feed)
            if r.returncode not in ok:
                raise _NotProvable(f'git-{args[0]}')
            return r

        def run(*args, feed=None, ok=(0,)):
            return run_in(env, source, *args, feed=feed, ok=ok)

        def has_commit(sha: str) -> bool:
            return run('cat-file', '-e', f'{sha}^{{commit}}', ok=(0, 1, 128)).returncode == 0

        # Where Git finds the user-wide config, attributes, excludes and template: relative, it names a
        # file next to the source here and next to the scratch target in the replay.
        for var in _PATH_ENV:
            if env.get(var) and not os.path.isabs(env[var]):
                raise _NotProvable(f'relative {var}')
        # Config, read here once from the replay's own config (user-wide, system and command line; the
        # source's local config never) and decided before the first index read. The same config gives
        # the same result here and in the replay only for what does not depend on where Git runs or on
        # a command only the replay runs: a key passes only when the proof models it (`_modelled_config`;
        # in the sections that steer a checkout, `_CHECKOUT_CONFIG` with the modelled value) and a path
        # it names is absolute. Any other key hands over by name, so a key not thought of costs a
        # replay, never a wrong acceptance.
        config = {}
        for record in run('config', '--list', '-z').stdout.split(b'\0'):
            if record:
                name, given, value = record.partition(b'\n')
                config[name.decode('utf-8', 'surrogateescape').lower()] = (
                    value.decode('utf-8', 'surrogateescape') if given else None)
        # A conditional include resolves by the repository that reads it: `onbranch` by its HEAD (the
        # replay checks out with HEAD on the unborn default branch of `git init` and fingerprints on the
        # recorded branch; this repository is detached), `gitdir` by its directory, `hasconfig` by its
        # remotes. Config is the same here and in the replay only without one, so any `includeIf`
        # reachable from this repository's config (through plain includes too) hands over.
        if any(name.startswith('includeif.') for name in config):
            raise _NotProvable('conditional-config')
        for name in config:
            if not _modelled_config(name):
                raise _NotProvable(_config_reason(name))
        # A relative path resolves against the work tree, the source's here and the scratch target's in
        # the replay. Git expands it (`~`), so the check sees the path Git opens; the last value counts.
        for name in _PATH_CONFIG:
            if name in config and not os.path.isabs(os.fsdecode(
                    run('config', '--type=path', '--get', name).stdout.rstrip(b'\n'))):
                raise _NotProvable(f'relative {name}')
        # Checkout conversions the proof does not model.
        crlf, eol = config.get('core.autocrlf', 'false'), config.get('core.eol', 'native')
        if ((crlf or '').strip().lower() != 'input' and _git_bool(crlf) is not False) or \
                eol is None or eol.strip().lower() not in ('lf', 'native'):
            raise _NotProvable('conversion')
        # Without symlinks the checkout writes a link as a file holding its target.
        if 'core.symlinks' in config and _git_bool(config['core.symlinks']) is not True:
            raise _NotProvable('symlinks')
        # Programs Git starts from configuration run in the work tree, here the source, and may change
        # what the replay sees: an fsmonitor is queried on every index read, a hook by the commands the
        # replay runs (its checkout, its fetch, the index refresh, which this proof runs too). None of
        # them starts here; a relative hooks path resolves against the work tree, the source's here and
        # the scratch target's in the replay.
        if 'core.fsmonitor' in config and _git_bool(config['core.fsmonitor']) is not False:
            raise _NotProvable('fsmonitor')
        def check_hooks(where: dict, cwd: Path) -> None:
            hooks = Path(os.fsdecode(run_in(where, cwd, 'rev-parse', '--git-path', 'hooks').stdout.rstrip(b'\n')))
            if not hooks.is_absolute() or any(
                    os.access(hooks / name, os.X_OK) and (hooks / name).is_file()
                    for name in ('post-checkout', 'post-index-change', 'reference-transaction', 'pre-auto-gc')):
                raise _NotProvable('hooks')
        check_hooks(env, source)
        # Submodules: their gitdirs made as the replay makes them, their recorded state compared; the
        # populated ones' environments read their HEAD trees below.
        inner = self._replay_submodules(checkpoint, data, source, env, check_hooks) \
            if data.get('submodules') else {}

        # Objects: the base and (no bundle) HEAD in the durable store, which the replay reaches too.
        if not has_commit(bundle['base']):
            raise _NotProvable('base')
        if bundle['mode'] == 'none' and not has_commit(head):
            raise _NotProvable('head')
        # A tracked path under an excluded or ignored one is restored from HEAD, not from the source, and
        # left out of the tree fingerprint: only the replay's `diff` can tell whether that agrees.
        if skip:
            for raw_name in run('ls-files', '-z').stdout.split(b'\0'):
                name = raw_name.decode('utf-8', 'surrogateescape')
                if name and any(p in skip for p in (*_parents(name), name)):
                    raise _NotProvable('skip-tracked')
            for root, where in inner.items():
                pre = root + '/'
                for raw_name in run_in(where, source / root, 'ls-files', '-z').stdout.split(b'\0'):
                    name = pre + raw_name.decode('utf-8', 'surrogateescape') if raw_name else ''
                    if name and any(p in skip for p in (*_parents(name), name)):
                        raise _NotProvable('skip-tracked')
        # The replay's tree: checkout of HEAD, minus `deleted` (files and links), then the delta files
        # over it (a directory in the way is removed whole), then the empty directories. Same steps,
        # same order as `_replay` / `_overlay_delta`; then each populated submodule the same way, from
        # its own HEAD and its own part of the delta (`_replay_submodule`), inside its gitlink's directory.
        outer, parts = _split_delta(delta, inner)
        pred = {}       # name -> ('dir',) | ('blob', mode, oid, repository) | ('delta',)

        def add_dir(name: str) -> None:
            for p in (*_parents(name), name):
                kind = pred.setdefault(p, ('dir',))[0]
                if kind != 'dir':
                    raise _NotProvable('layout')        # the replay's mkdir would fail or follow a link

        def lay_out(listing: bytes, part: dict, prefix: str = '') -> None:
            pre = prefix + '/' if prefix else ''
            for record in listing.split(b'\0'):
                if not record:
                    continue
                meta, _, raw = record.partition(b'\t')
                mode, kind, oid = meta.decode('ascii').split()
                name = pre + raw.decode('utf-8', 'surrogateescape')
                if '/' in name:
                    add_dir(name.rsplit('/', 1)[0])
                if mode == '160000' and not prefix:
                    pred[name] = ('dir',)               # a placeholder: checkout makes it an empty directory
                elif kind == 'blob' and mode in ('100644', '100755', '120000'):
                    pred[name] = ('blob', mode, oid, prefix)
                else:
                    raise _NotProvable('mode')
            for name in part['deleted']:
                if any(pred.get(p, ('dir',))[0] != 'dir' for p in _parents(name)):
                    raise _NotProvable('layout')
                have = pred.get(name)
                if have is None or have[0] == 'dir':
                    continue                             # the replay unlinks only what is not a directory
                if have[1] == '120000':
                    raise _NotProvable('deleted-link')   # kept or removed depending on where it points
                del pred[name]
            for name in sorted(part['files']):
                if '/' in name:
                    add_dir(name.rsplit('/', 1)[0])
                if pred.get(name, ('',))[0] == 'dir':
                    for k in [k for k in pred if k.startswith(name + '/')]:
                        del pred[k]
                pred[name] = ('delta',)
            for name in part['dirs']:
                add_dir(name)

        lay_out(run('ls-tree', '-r', '-z', '--full-tree', head).stdout, outer)
        for root, where in inner.items():
            if pred.get(root) != ('dir',):
                raise _NotProvable('layout')
            lay_out(run_in(where, source / root, 'ls-tree', '-r', '-z', '--full-tree', 'HEAD').stdout,
                    parts[root], root)

        def skipped(name: str) -> bool:
            return any(p in skip for p in (*_parents(name), name))
        pred = {k: v for k, v in pred.items() if not skipped(k)}
        if set(pred) != set(full):
            raise _NotProvable('layout')
        def marked(entry) -> bool:
            return isinstance(entry, list) and len(entry) > 2 and entry[0] == 'dir' and entry[2] == NESTED
        files, links = {}, {}
        for name, want in full.items():
            have = pred[name]
            if have[0] == 'delta':
                if want[0] not in ('file', 'link'):
                    raise _NotProvable('layout')
                continue                                 # the delta tree inventory above matched it
            if have[0] == 'dir':
                if want[0] != 'dir':
                    raise _NotProvable('layout')
                # `inventory` marks a nested repository by its `.git`, outside any other one only.
                nested = f'{name}/.git' in pred and not any(marked(full.get(p)) for p in _parents(name))
                if nested != marked(want):
                    raise _NotProvable('layout')
                continue
            _, mode, oid, repo = have
            if (mode == '120000') != (want[0] == 'link') or want[0] not in ('file', 'link'):
                raise _NotProvable('layout')
            (links if mode == '120000' else files).setdefault((repo, oid), []).append(name)
        for repo in sorted({r for r, _ in (*files, *links)}):
            where, cwd = (inner[repo], source / repo) if repo else (env, source)
            cut = len(repo) + 1 if repo else 0          # a submodule's git names its paths from its root
            mine = {oid: names for (r, oid), names in files.items() if r == repo}
            if mine:
                # The attributes the replay's checkout applies: HEAD's `.gitattributes` (the work tree's
                # agree, see above), the user's attributes file, the replay repository's `info/attributes`.
                fields = run_in(where, cwd, 'check-attr', '-z', '--stdin', 'filter', 'ident',
                                'working-tree-encoding', 'eol',
                                feed=b''.join(n[cut:].encode('utf-8', 'surrogateescape') + b'\0'
                                              for names in mine.values() for n in names)).stdout.split(b'\0')
                for attr, value in zip(fields[1::3], fields[2::3]):
                    if (attr == b'eol' and value == b'crlf') or (
                            attr != b'eol' and value not in (b'unspecified', b'unset')):
                        raise _NotProvable('conversion')
            # Content: every HEAD blob the replay writes must hash to what the capture recorded there.
            kept = {oid: names for (r, oid), names in links.items() if r == repo}
            digests = _blob_digests(cwd, sorted({*mine, *kept}), set(kept), env=where)
            for oid, names in mine.items():
                size, sha, _ = digests[oid]
                if any(full[n][2] != size or full[n][3] != sha for n in names):
                    raise _NotProvable('content')
            for oid, names in kept.items():
                target = os.fsdecode(digests[oid][2])
                if any(full[n][2] != target for n in names):
                    raise _NotProvable('content')
        if self._replay_view(data, source, env) != {
                k: data['fingerprint'][k] for k in ('head', 'staged', 'unstaged', 'status')}:
            raise _NotProvable('git-view')

    @staticmethod
    def _replay_view(data: dict, source: Path, env: dict) -> dict:
        """head, staged, unstaged and status as `fingerprint` computes them on the replay's target, without
        the target: in the replay's repository (`_replay_repo`), the stored index refreshed as the replay
        refreshes it. The source holds the same files as the target (the tree proof); what the replay
        leaves out (ignored and excluded paths) is left out here by pathspec."""
        excludes, ignored = tuple(data.get('excludes', [])), tuple(data.get('ignored', []))

        def raw(*args):
            r = _run(['git', '-C', str(source), *args], capture_output=True, env=env)
            if r.returncode:
                raise _NotProvable(f'git-{args[0]}')
            return r.stdout
        # As the replay does before its fingerprint; writes the probe's copy of the index only.
        _run(['git', '-C', str(source), 'update-index', '--really-refresh'], capture_output=True, env=env)
        roots = tuple(e['path'] for e in data.get('submodules') or [] if e['populated'])
        left_out = tuple(e for e in (*excludes, *ignored)
                         if not any(e == r or e.startswith(r + '/') for r in roots))
        spec = ['--', '.', *(f':(exclude,literal){e}' for e in left_out)] if left_out else []
        return {'head': raw('rev-parse', 'HEAD').decode('ascii').strip(),
                'staged': hashlib.sha256(raw('diff', '--cached', '--binary', '--no-ext-diff')).hexdigest(),
                'unstaged': hashlib.sha256(raw('diff', '--binary', '--no-ext-diff')).hexdigest(),
                'status': hashlib.sha256(raw('status', '--porcelain=v1', '-z', '--untracked-files=all',
                                             *spec)).hexdigest()}

    def verify(self, checkpoint: Path, in_place: bool = False) -> None:
        with _IO_LOCK:
            self._verify(checkpoint, in_place)

    def preflight(self, checkpoint: Path) -> None:
        """The stored bytes are still those the capture proved, mostly without a replay: the tree matches
        its recorded inventory and every git index the replay copies into the target is the one captured
        (its recorded sha256; a snapshot taken before those were recorded: its checksum, or, for an index
        git wrote without one, a replay into scratch as before). A replay copies the tree and the indexes
        into the target before it checks the result, so damage found only there costs the target slot; the
        commits are proven by the restore before it touches the target. Raises WorkspaceError naming the
        damaged component."""
        with _IO_LOCK:
            data = self.read(checkpoint)
            subs = data.get('submodules', [])
            delta = data.get('delta')
            expected = _delta_keep(data['fingerprint']['tree'], delta) if delta else data['fingerprint']['tree']
            if inventory(checkpoint / 'tree', tuple(e['path'] for e in subs if e['populated'])) != expected:
                raise WorkspaceError('checkpoint: snapshot hash mismatch')
            names = ['index'] + [f'submodules/{i}/index'
                                 for i, e in enumerate(subs) if e['gitdir'] and e['populated']]
            recorded = data.get('index_sha256')
            if recorded is not None:
                allowed = {'index', *(f'submodules/{i}/index' for i in range(len(subs)))}
                if (not isinstance(recorded, dict) or not set(recorded) <= allowed
                        or not all(isinstance(v, str) for v in recorded.values())):
                    raise WorkspaceError('checkpoint: invalid manifest')
                names += sorted(set(recorded) - set(names))
            unproven = False
            for name in names:
                digest = None if recorded is None else recorded.get(name, '')     # unrecorded: refused
                if not _index_whole(checkpoint / name, digest):
                    raise WorkspaceError(f'checkpoint: index damaged: {name}')
                unproven = unproven or (digest is None and _index_skiphash(checkpoint / name))
            if unproven:
                # A snapshot taken before the digests, whose index git wrote without a checksum: its form
                # does not show a changed entry, so it is proven as before, by a replay into scratch.
                self._verify(checkpoint)

    def _verify(self, checkpoint: Path, in_place: bool = False) -> None:
        """Prove the snapshot restores to its fingerprint by replaying it into scratch: a checkout of the
        whole tree, removed after. `in_place` (the capture's own check, while its source still holds the
        recorded tree) first tries `_prove_in_place`, which lays no tree out, and replays only what that
        cannot decide. On every path a slim bundle's pack is indexed onto the durable store first: the
        replay's fetch reads no pack whose tips that store already holds."""
        _mark('verify-setup')
        data = self.read(checkpoint)
        bundle = data.get('bundle')
        if bundle and bundle.get('mode') != 'none':
            objects = _durable_objects(data)
            if objects is None:
                raise WorkspaceError('checkpoint: bundle base unavailable')
            _mark('verify-pack')
            self._prove_bundle(checkpoint / 'commits.bundle',
                               ['+refs/*:refs/runner-replay/*', *(['HEAD'] if bundle['has_head'] else [])],
                               'bundle invalid', reference=objects, whole_pack=True)
        if in_place:
            try:
                self._prove_in_place(checkpoint, data)
                return
            except _NotProvable as e:
                log.info("checkpoint %s: proof in place not decided (%s); scratch replay", checkpoint.name[:40],
                         e.reason)
            _mark('verify-setup')
        self._budget(self.root, data['bytes'] + 2 * data['object_bytes'])
        with tempfile.TemporaryDirectory(prefix='.verify-', dir=self.root) as name:
            target = Path(name)
            git(target, 'init', '--quiet')
            if data.get('bundle'):
                objects = _durable_objects(data)
                if objects is None:
                    raise WorkspaceError('checkpoint: bundle base unavailable')
                _alternate(target / '.git' / 'objects', objects)
            self._replay(checkpoint, target, prove=False)

    def is_old_format(self, checkpoint: Path) -> bool:
        """True for a snapshot that predates the slim form (full tree, full bundle), or the cache-exclusion
        format and still holds some caches: `compact` rewrites it."""
        data = self.read(checkpoint)
        if 'delta' in data:
            return False        # slim form: caches are never in a delta tree
        if self.slim and not data.get('slim_failed') and not data.get('submodules'):
            return True
        if 'excludes' in data:
            return False
        return any(name in self.exclude_names for rel in data['fingerprint']['tree']
                   for name in Path(rel).parts)

    def compact(self, checkpoint: Path, base_objects: Path | None = None,
                expected_manifest_sha: str | None = None) -> dict:
        """Rewrite an old-format snapshot in place as a new-format one (same directory name).

        The old snapshot is replayed into scratch (hash-verified against its own fingerprint), a new
        snapshot is captured from that scratch and replay-verified, and only then the directory is
        swapped. Any failure leaves the old snapshot untouched. Returns {'compacted', 'before', 'after'}.

        The capture slot is usually gone by now. The base commit is taken from the object store the
        manifest records, else from `base_objects` (the pool's base clone, for a manifest written
        before `objects` was recorded); `CheckpointBaseMissing` when that store lacks it."""
        with _IO_LOCK:
            return self._compact(checkpoint, base_objects, expected_manifest_sha)

    def _compact(self, checkpoint: Path, base_objects: Path | None = None,
                 expected_manifest_sha: str | None = None) -> dict:
        def check_pin():
            if expected_manifest_sha is not None and manifest_digest(checkpoint) != expected_manifest_sha:
                raise WorkspaceError('checkpoint pin: manifest drift')
        check_pin()
        retired = self.root / f'.retired-{checkpoint.name}'
        if not self.is_old_format(checkpoint):
            return {'compacted': False}
        data = self.read(checkpoint)
        if data.get('submodules'):
            # Not supported: recapture of configured submodules. Reported, never silent.
            return {'compacted': False, 'skipped': 'submodules'}
        before = _du(checkpoint)
        key = f'compact-{uuid.uuid4().hex}'     # unique: never names an existing checkpoint
        created = self.root / key
        scratch = Path(tempfile.mkdtemp(prefix='.compact-src-', dir=self.root))
        try:
            self._budget(self.root, data['bytes'] + 3 * data['object_bytes'], self.capture_min_free_bytes)
            git(scratch, 'init', '--quiet')
            # The scratch borrows the durable store, as a pool slot does: a slim replay finds its base
            # there, and the new capture bundles only what the base lacks, so it verifies from there too.
            objects = _durable_objects(data, base_objects)
            base = (data.get('bundle') or {}).get('base') or data['metadata'].get('base_sha')
            if objects is not None:
                _alternate(scratch / '.git' / 'objects', objects)
            if base and objects is None:
                raise WorkspaceError('checkpoint: bundle base unavailable')
            if base and not _has_commit(scratch, base):
                raise CheckpointBaseMissing('checkpoint: bundle base missing from the base clone')
            self._replay(checkpoint, scratch, prove=True)
            self._create_best(key, scratch, data['metadata'])
            manifest = self.read(created)
            if (manifest['fingerprint']['head'] != data['fingerprint']['head']
                    or manifest['metadata'] != data['metadata'] or manifest.get('branch') != data.get('branch')):
                raise WorkspaceError('checkpoint: compacted snapshot differs in head/metadata/branch')
            manifest['source'] = data['source']
            if objects is not None:
                manifest['objects'] = str(objects)
            else:
                manifest.pop('objects', None)       # the scratch store is about to be deleted
            atomic_json(created / 'manifest.json', manifest)
            self._verify(created)
            check_pin()
            os.rename(checkpoint, retired)
            try:
                os.rename(created, checkpoint)
            except BaseException:
                os.rename(retired, checkpoint)      # never leave the only copy under .retired-
                raise
            _sync(self.root)
            _rmtree(retired, ignore_errors=True)
            return {'compacted': True, 'before': before, 'after': _du(checkpoint)}
        finally:
            _rmtree(scratch, ignore_errors=True)
            _rmtree(created, ignore_errors=True)

    @staticmethod
    def _marker(target: Path) -> Path:
        path = Path(git(target, 'rev-parse', '--git-path', RESTORE_MARKER))
        return path if path.is_absolute() else target / path

    @staticmethod
    def _result_digest(data: dict) -> str:
        return hashlib.sha256(json.dumps(data['fingerprint'], sort_keys=True).encode()).hexdigest()

    def restore(self, checkpoint: Path, target: Path) -> dict:
        """Replay over target. A completed restore leaves a marker holding the digest of its
        result; a later restore of the same checkpoint refuses if target moved on since. An
        in-progress marker for this checkpoint, or no marker at all (fresh/freed slot, or an
        earlier runner killed mid-replay), allows retrying over a provably partial replay. Any
        unexpected, corrupt, symlinked or foreign restore marker fails closed."""
        with _IO_LOCK:
            data = self.read(checkpoint)
            expected_digest = self._result_digest(data)
            marker = self._marker(target)
            completed = False
            done = None
            if os.path.lexists(marker):
                if marker.is_symlink() or not marker.is_file():
                    raise RestoreRefused('checkpoint: unexpected or unreadable restore marker in target; refused')
                try:
                    done = json.loads(marker.read_text())
                except (OSError, ValueError):
                    raise RestoreRefused('checkpoint: unexpected or unreadable restore marker in target; refused') from None
                if not isinstance(done, dict):
                    raise RestoreRefused('checkpoint: unexpected or unreadable restore marker in target; refused')
                if done.get('checkpoint') == checkpoint.name and 'replaying' not in done:
                    completed = True
                elif (done.get('replaying') == checkpoint.name
                      and 'checkpoint' not in done
                      and done.get('result') == expected_digest):
                    completed = False
                else:
                    raise RestoreRefused('checkpoint: restore marker belongs to another checkpoint or state; refused')
            if completed:
                # Submodule-specific refusals first: the plain fingerprint cannot see inside a populated submodule.
                self._check_target_submodules(checkpoint, target, data, completed=True)
                current = hashlib.sha256(json.dumps(
                    fingerprint(target, data.get('submodules'), tuple(data.get('excludes', [])),
                                tuple(data.get('ignored', []))), sort_keys=True).encode()).hexdigest()
                if current != done.get('result'):
                    raise RestoreRefused('checkpoint: target has newer work since completed restore; refused')
            self._budget(target, data['bytes'] + data['object_bytes'])
            self._replay(checkpoint, target, completed=completed, marker=marker)
            atomic_json(marker, {'checkpoint': checkpoint.name, 'result': expected_digest})
            return data

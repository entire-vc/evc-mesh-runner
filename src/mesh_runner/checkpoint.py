def _du(path: Path) -> int:
    r = _run(['du', '-sk', str(path)], capture_output=True, text=True)
    return int(r.stdout.split()[0]) * 1024 if r.returncode == 0 and r.stdout else 0


def _sync(path: Path) -> None:
    fd = os.open(path, os.O_RDONLY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


def atomic_json(path: Path, value: dict) -> None:
    tmp = path.with_suffix('.tmp')
    with open(tmp, 'w', opener=lambda p, f: os.open(p, f, 0o600)) as out:
        json.dump(value, out, sort_keys=True)
        out.flush()
        os.fsync(out.fileno())
    os.replace(tmp, path)
    _sync(path.parent)


def inventory(root: Path, submodules: tuple = (), excludes: frozenset = frozenset()) -> dict:
    """Hash contents/modes without following links; reject sockets/devices/nested repos.

    `submodules` lists the worktree paths whose `.git` pointer file is replaced on restore.
    `excludes` lists relative directory paths left out of the snapshot (not walked, not hashed).
    """
    result = {}
    pointers = {f'{p}/.git' for p in submodules}
    def walk(path: Path):
        for child in sorted(path.iterdir()):
            name = child.relative_to(root).as_posix()
            if name == '.git' or name in excludes:
                continue
            s = child.lstat()
            if name in pointers and stat.S_ISREG(s.st_mode):
                continue
            if child.name == '.git':
                raise WorkspaceError('checkpoint: nested repository unsupported')
            mode = stat.S_IMODE(s.st_mode)
            if stat.S_ISLNK(s.st_mode):
                result[name] = ['link', mode, os.readlink(child)]
            elif stat.S_ISDIR(s.st_mode):
                result[name] = ['dir', mode]
                walk(child)
            elif stat.S_ISREG(s.st_mode):
                h = hashlib.sha256()
                with child.open('rb') as stream:
                    for block in iter(lambda: stream.read(1024 * 1024), b''):
                        h.update(block)
                result[name] = ['file', mode, s.st_size, h.hexdigest()]
            else:
                raise WorkspaceError('checkpoint: special file unsupported')
    walk(root)
    return result


def _modules_dir(path: Path) -> Path:
    modules = Path(git(path, 'rev-parse', '--git-path', 'modules'))
    return modules if modules.is_absolute() else path / modules


def _gitdir(gd: Path, *args: str, check: bool = True) -> str:
    r = _run(['git', '--git-dir', str(gd), '--work-tree', str(gd), *args], capture_output=True, text=True,
                       errors='surrogateescape')
    if check and r.returncode:
        raise WorkspaceError(f'checkpoint: git {args[0]} failed in a submodule gitdir: {r.stderr.strip()[:120]}')
    return r.stdout.strip()


def _stash_create(repo: Path) -> str:
    """`git stash create`, also for an index holding intent-to-add (`git add -N`) entries.

    Git refuses to stash those ("Entry ... not uptodate. Cannot merge."), which kept the
    workspace from suspending. Retry on a scratch copy of the index in which those
    paths are really added; the real index is untouched (the checkpoint stores it as is).
    """
    try:
        return git(repo, 'stash', 'create')
    except WorkspaceError:
        # read the NUL-separated list raw: git() strips its output, which would cut a
        # leading space from the first path
        res = _run(['git', '-C', str(repo), 'diff', '--name-only', '-z', '--diff-filter=A'],
                             capture_output=True, text=True, errors='surrogateescape',
                             env=dict(os.environ, GIT_TERMINAL_PROMPT='0'), timeout=600)
        added = [n for n in res.stdout.split('\0') if n] if res.returncode == 0 else []
        if not added:
            raise
    index = Path(git(repo, 'rev-parse', '--git-path', 'index'))
    if not index.is_absolute():
        index = repo / index
    with tempfile.TemporaryDirectory(prefix='.ita-index-') as scratch:
        tmp = Path(scratch) / 'index'
        shutil.copy2(index, tmp)
        env = dict(os.environ, GIT_INDEX_FILE=str(tmp))
        git(repo, 'add', '-f', '--', *added, env=env)
        return git(repo, 'stash', 'create', env=env)


def _safe_rel(name: str) -> bool:
    p = Path(name)
    return bool(name) and not p.is_absolute() and '..' not in p.parts and '.git' not in p.parts


def _submodule_names(source: Path) -> dict:
    """gitlink path -> submodule name, from the worktree .gitmodules (never from config values)."""
    r = _run(['git', '-C', str(source), 'config', '-f', '.gitmodules', '-z',
                        '--get-regexp', '^submodule\\..*\\.path$'], capture_output=True)
    if r.returncode not in (0, 1):
        raise WorkspaceError('checkpoint: configured submodule metadata unsupported')
    names = {}
    for item in r.stdout.split(b'\0'):
        if not item:
            continue
        key, _, value = item.partition(b'\n')
        try:
            names[value.decode('utf-8')] = key.decode('utf-8')[len('submodule.'):-len('.path')]
        except UnicodeDecodeError:
            raise WorkspaceError('checkpoint: non-UTF8 gitlink path unsupported') from None
    return names


def submodule_plan(source: Path) -> list:
    """Validate gitlinks and return one entry per configured submodule (empty for placeholders).

    Absent/empty placeholders without any submodule metadata need no external repo data: the
    parent commit/index preserves their OIDs. Configured submodules are supported one level deep
    when every gitlink maps to a `.gitmodules` name and its gitdir lives in this worktree's own
    modules directory. Never follow a symlink or claim an unverifiable state was checkpointed.
    """
    result = _run(['git', '-C', str(source), 'ls-files', '--stage', '-z'],
                            capture_output=True)
    if result.returncode:
        raise WorkspaceError('checkpoint: cannot inspect gitlinks')
    records = [record for record in result.stdout.split(b'\0') if record.startswith(b'160000 ')]
    head = _run(['git', '-C', str(source), 'ls-tree', '-r', '-z', 'HEAD'], capture_output=True)
    if head.returncode:
        raise WorkspaceError('checkpoint: cannot inspect HEAD gitlinks')
    head_links = {r.split(b'\t', 1)[1] for r in head.stdout.split(b'\0') if r.startswith(b'160000 ')}
    index_links = {r.split(b'\t', 1)[1] for r in records}
    if head_links - index_links:
        raise WorkspaceError('checkpoint: removed or replaced gitlink unsupported')
    if not records:
        return []
    configured = _run(['git', '-C', str(source), 'config',
                                 '--name-only', '--get-regexp', '^submodule\\.'], capture_output=True)
    if configured.returncode not in (0, 1):
        raise WorkspaceError('checkpoint: cannot inspect submodule configuration')
    modules = _modules_dir(source)
    metadata = bool(os.path.lexists(source / '.gitmodules') or configured.stdout
                    or git(source, 'ls-files', '--', '.gitmodules')
                    or git(source, 'ls-tree', '--name-only', 'HEAD', '.gitmodules')
                    or os.path.lexists(modules))
    names = _submodule_names(source) if metadata and os.path.lexists(source / '.gitmodules') else {}
    plan = []
    for record in records:
        header, raw_name = record.split(b'\t', 1)
        try:
            name = Path(raw_name.decode('utf-8'))
        except UnicodeDecodeError:
            raise WorkspaceError('checkpoint: non-UTF8 gitlink path unsupported') from None
        if header.split()[2] != b'0' or name.is_absolute() or '..' in name.parts:
            raise WorkspaceError('checkpoint: unmerged or unsafe gitlink unsupported')
        populated = False
        current = source
        for part in name.parts:
            current = current / part
            try:
                mode = current.lstat().st_mode
            except FileNotFoundError:
                break  # absent placeholder, including an absent parent
            if not stat.S_ISDIR(mode):
                raise WorkspaceError('checkpoint: symlink or non-directory gitlink unsupported')
        else:
            populated = any(current.iterdir())
        if not metadata:
            if populated:
                raise WorkspaceError('checkpoint: populated submodule unsupported')
            continue
        sub = name.as_posix()
        if sub not in names or not _safe_rel(names[sub]) or '.git' in Path(sub).parts:
            raise WorkspaceError('checkpoint: configured submodule metadata unsupported')
        plan.append({'path': sub, 'name': names[sub], 'populated': populated,
                     'gitdir': os.path.lexists(modules / names[sub])})
    if not metadata:
        return []
    # Everything under our modules directory must belong to a listed gitlink.
    known = {Path(e['name']).parts[0] for e in plan}
    if os.path.lexists(modules):
        if modules.is_symlink() or not modules.is_dir():
            raise WorkspaceError('checkpoint: configured submodule metadata unsupported')
        if any(child.name not in known for child in modules.iterdir()):
            raise WorkspaceError('checkpoint: configured submodule metadata unsupported')
    _check_locks(source, modules, plan)
    for e in plan:
        gd = modules / e['name']
        wt = source / e['path']
        if e['gitdir']:
            for part in [gd, *gd.parents]:
                if part == modules.parent:
                    break
                if part.is_symlink():
                    raise WorkspaceError('checkpoint: symlinked submodule gitdir unsupported')
            if not gd.is_dir() or os.path.lexists(gd / 'modules'):
                raise WorkspaceError('checkpoint: recursive submodule unsupported')
        if e['populated']:
            pointer = wt / '.git'
            if not e['gitdir'] or pointer.is_symlink() or not pointer.is_file() or pointer.stat().st_size > 4096:
                raise WorkspaceError('checkpoint: populated submodule unsupported')
            text = pointer.read_text(errors='surrogateescape')
            if not text.startswith('gitdir: ') or '\n' in text.strip():
                raise WorkspaceError('checkpoint: populated submodule unsupported')
            if os.path.realpath(wt / text[len('gitdir: '):].strip()) != os.path.realpath(gd):
                raise WorkspaceError('checkpoint: submodule gitdir outside own modules unsupported')
            inner = _run(['git', '-C', str(wt), 'ls-files', '--stage', '-z'], capture_output=True)
            if inner.returncode:
                raise WorkspaceError('checkpoint: cannot inspect submodule')
            if any(r.startswith(b'160000 ') for r in inner.stdout.split(b'\0')):
                raise WorkspaceError('checkpoint: recursive submodule unsupported')
            if _gitdir(gd, 'rev-parse', '--verify', '-q', 'HEAD', check=False) == '':
                raise WorkspaceError('checkpoint: unborn submodule unsupported')
        elif e['gitdir'] and _gitdir(gd, 'rev-parse', '--verify', '-q', 'HEAD', check=False) == '':
            raise WorkspaceError('checkpoint: unborn submodule unsupported')
    return plan


def _check_locks(source: Path, modules: Path, plan: list) -> None:
    gitdirs = [Path(git(source, 'rev-parse', '--absolute-git-dir'))]
    gitdirs += [modules / e['name'] for e in plan if e['gitdir']]
    if any(os.path.lexists(g / lock) for g in gitdirs for lock in ('index.lock', 'HEAD.lock')):
        raise WorkspaceError('checkpoint: active git writer; lease retained')


def _submodule_state(path: Path, entry: dict, modules: Path) -> dict:
    gd = modules / entry['name']
    if not os.path.lexists(gd):
        return {'gitdir': False}
    state = {'gitdir': True, 'head': _gitdir(gd, 'rev-parse', '--verify', 'HEAD'),
             'branch': _gitdir(gd, 'symbolic-ref', '--quiet', 'HEAD', check=False),
             'refs': hashlib.sha256('\n'.join(
                 line[1:] for line in _gitdir(gd, 'for-each-ref', '--format=%(symref)|%(refname) %(objectname)',
                                               'refs/heads', 'refs/tags', 'refs/remotes').splitlines()
                 if line.startswith('|')  # symbolic refs (origin/HEAD) are not bundled
             ).encode(errors='surrogateescape')).hexdigest()}
    wt = path / entry['path']
    if (wt / '.git').is_file():
        def raw(*args):
            r = _run(['git', '-C', str(wt), *args], capture_output=True)
            if r.returncode:
                raise WorkspaceError('checkpoint: cannot fingerprint submodule state')
            return hashlib.sha256(r.stdout).hexdigest()
        state.update(staged=raw('diff', '--cached', '--binary', '--no-ext-diff'),
                     unstaged=raw('diff', '--binary', '--no-ext-diff'),
                     status=raw('status', '--porcelain=v1', '-z', '--untracked-files=all'))
    return state


def _repo_unique_work(gd: Path) -> str:
    """Why this gitdir holds something no remote has; empty when it is only a clone of one.

    Strict about refs: a local branch must equal a remote-tracking branch of the same name, a
    tag must be one the clone received (recorded unchanged in packed-refs; a tag made or
    fetched later is loose and counts as local), and no ref may live outside heads, tags and
    remotes. Every commit must also be reachable from a remote-tracking ref."""
    refs = []
    for line in _gitdir(gd, 'for-each-ref', '--format=%(refname) %(objectname)', check=False).splitlines():
        name, _, oid = line.rpartition(' ')
        refs.append((name, oid))
    if any(not n.startswith(('refs/heads/', 'refs/tags/', 'refs/remotes/')) for n, _ in refs):
        return 'extra refs such as a stash'
    remote = {(n.split('/', 3)[3], o) for n, o in refs if n.startswith('refs/remotes/') and n.count('/') >= 3}
    for n, o in refs:
        if n.startswith('refs/heads/') and (n[len('refs/heads/'):], o) not in remote:
            return f'local branch {n[len("refs/heads/"):]} is not a remote-tracking branch'
    tags = [(n, o) for n, o in refs if n.startswith('refs/tags/')]
    if tags:
        packed = {}
        try:
            for line in (gd / 'packed-refs').read_text(errors='surrogateescape').splitlines():
                if line and line[0] not in '#^' and ' ' in line:
                    oid, _, name = line.partition(' ')
                    packed[name] = oid
        except OSError:
            pass
        for n, o in tags:
            if packed.get(n) != o:
                return f'local tag {n[len("refs/tags/"):]}'
    if not _gitdir(gd, 'rev-parse', '--verify', '-q', 'HEAD', check=False):
        return 'unborn HEAD'
    if _gitdir(gd, 'rev-list', '-n', '1', 'HEAD', '--branches', '--tags', '--not', '--remotes', check=False):
        return 'commits not on any remote'
    return ''


def _stale_submodule_work(target: Path, entry: dict, gd: Path) -> str:
    """Why a submodule left in a pooled slot may NOT be set aside; empty when it is disposable.

    Disposable means a leftover of an earlier lease: no nested submodule state anywhere (a
    nested level is refused, not inspected), every commit and ref also on a remote, and a
    worktree that is absent, empty or clean (nothing staged, modified or untracked).
    Anything else may be someone's work."""
    # Nested submodules are not inspected: any sign of one makes the leftover unsafe to set aside.
    if not gd.is_dir():
        return 'not a plain gitdir'
    if os.path.lexists(gd / 'modules'):
        return 'nested submodule state in the gitdir'
    why = _repo_unique_work(gd)
    if why:
        return why
    wt = target / entry['path']
    if not os.path.lexists(wt):
        return ''
    if wt.is_symlink() or not wt.is_dir():
        return 'worktree is not a directory'
    if not any(wt.iterdir()):
        return ''
    pointer = wt / '.git'
    if pointer.is_symlink():
        return 'worktree .git is a symlink'
    if pointer.is_file():
        text = pointer.read_text(errors='surrogateescape')
        if (not text.startswith('gitdir: ') or '\n' in text.strip()
                or os.path.realpath(wt / text[len('gitdir: '):].strip()) != os.path.realpath(gd)):
            return 'worktree points at another gitdir'
    elif pointer.is_dir():
        if any(os.path.lexists(pointer / lock) for lock in ('index.lock', 'HEAD.lock')):
            return 'active git writer in the worktree'
        if os.path.lexists(pointer / 'modules'):
            return 'nested submodule state in the worktree repository'
        why = _repo_unique_work(pointer)
        if why:
            return 'worktree repository: ' + why
    else:
        return 'worktree holds files outside any repository'
    for root, dirs, files in os.walk(wt):
        if root == str(wt):
            dirs[:] = [d for d in dirs if d != '.git']
            files = [f for f in files if f != '.git']
        if '.git' in dirs or '.git' in files:
            return 'nested repository in the worktree'
    status = _run(['git', '--no-optional-locks', '-C', str(wt), 'status', '--porcelain=v1', '-z',
                             '--untracked-files=all'], capture_output=True)
    if status.returncode or status.stdout:
        return 'uncommitted or untracked work'
    return ''


def find_excludes(source: Path, names: tuple) -> list:
    """Outermost directories called one of `names` with no tracked file beneath them."""
    if not names:
        return []
    r = _run(['git', '-C', str(source), 'ls-files', '-z'], capture_output=True)
    if r.returncode:
        raise WorkspaceError('checkpoint: cannot list tracked files')
    tracked = set()  # tracked directories, and gitlinks (a submodule's own files are not listed here)
    for item in r.stdout.split(b'\0'):
        if not item:
            continue
        full = Path(item.decode('utf-8', 'surrogateescape'))
        tracked.add(full.as_posix())
        tracked.update('/'.join(full.parts[:i]) for i in range(1, len(full.parts)))
    found = []
    def walk(path: Path):
        for child in sorted(path.iterdir()):
            if child.name == '.git' or child.is_symlink() or not child.is_dir():
                continue
            name = child.relative_to(source).as_posix()
            if name in tracked and (source / name / '.git').exists():
                continue  # populated submodule: its tracked files live in its own repository
            if child.name in names and name not in tracked:
                found.append(name)
            else:
                walk(child)
    walk(source)
    return found


def _copy(src: Path, dst: Path, excludes: frozenset = frozenset()) -> None:
    # APFS clones use no second full allocation. Portable fallback is budgeted below.
    if sys.platform == 'darwin':
        def copyfile(a, b):
            r = _run(['cp', '-cp', str(a), str(b)], capture_output=True)
            if r.returncode:
                shutil.copy2(a, b)
            return b
    else:
        copyfile = shutil.copy2
    shutil.copytree(src, dst, symlinks=True, copy_function=copyfile,
                    ignore=lambda p, names: [n for n in names if (Path(p) == src and n == '.git')
                                             or (Path(p) / n).relative_to(src).as_posix() in excludes])


def _clear_tree(root: Path) -> None:
    # Called only for an owned lease after a durable checkpoint; never on a base clone.
    for child in root.iterdir():
        if child.name == '.git':
            continue
        if child.is_dir() and not child.is_symlink():
            shutil.rmtree(child)
        else:
            child.unlink()


def fingerprint(path: Path, submodules: list | None = None, excludes: tuple = (), ignored: tuple = ()) -> dict:
    # Untracked-but-not-ignored excluded dirs show up in `status`; leave them out of it too.
    spec = ['--', '.', *(f':(exclude,literal){e}' for e in excludes)] if excludes else []
    def raw(*args):
        r = _run(['git', '-C', str(path), *args], capture_output=True)
        if r.returncode:
            raise WorkspaceError('checkpoint: cannot fingerprint git state')
        return hashlib.sha256(r.stdout).hexdigest()
    subs = submodules or []
    result = {'head': git(path, 'rev-parse', 'HEAD'),
              'staged': raw('diff', '--cached', '--binary', '--no-ext-diff'),
              'unstaged': raw('diff', '--binary', '--no-ext-diff'),
              'status': raw('status', '--porcelain=v1', '-z', '--untracked-files=all', *spec),
              'tree': inventory(path, tuple(e['path'] for e in subs if e['populated']), frozenset((*excludes, *ignored)))}
    if subs:
        modules = _modules_dir(path)
        result['submodules'] = {e['path']: _submodule_state(path, e, modules) for e in subs}
    return result


MAX_UNTRACKED_BYTES = 16 * 1024 * 1024    # an untracked file above this is not worth a snapshot slot


def _status_entries(source: Path) -> list:
    """(XY, path, orig) for every changed/untracked path, as git sees it; ignored paths are absent."""
    r = _run(['git', '-C', str(source), 'status', '--porcelain=v1', '-z', '--untracked-files=all'],
                       capture_output=True)
    if r.returncode:
        raise WorkspaceError('checkpoint: cannot list changed files')
    parts = r.stdout.split(b'\0')
    out, i = [], 0
    while i < len(parts):
        item = parts[i]
        i += 1
        if len(item) < 4:
            continue
        xy, name = item[:2].decode(), item[3:].decode('utf-8', 'surrogateescape')
        orig = None
        if 'R' in xy or 'C' in xy:
            orig = parts[i].decode('utf-8', 'surrogateescape') if i < len(parts) else None
            i += 1
        out.append((xy, name, orig))
    return out


def find_ignored(source: Path, covered: list) -> list:
    """Git-ignored paths (outermost), minus what a named exclude already covers: logs, caches and
    build output that any clone regenerates. Tracked files are never listed here."""
    r = _run(['git', '-C', str(source), 'ls-files', '-z', '--others', '--ignored', '--exclude-standard',
                        '--directory'], capture_output=True)
    if r.returncode:
        raise WorkspaceError('checkpoint: cannot list ignored files')
    found = []
    for item in r.stdout.split(b'\0'):
        name = item.decode('utf-8', 'surrogateescape').rstrip('/')
        if name and name != '.git' and not any(name == c or name.startswith(c + '/') for c in covered):
            found.append(name)
    return found


def find_large_untracked(source: Path, covered: list, limit: int) -> list:
    out = []
    for xy, name, _ in _status_entries(source):
        if xy != '??' or any(name == c or name.startswith(c + '/') for c in covered):
            continue
        try:
            if (source / name).lstat().st_size > limit and not (source / name).is_symlink():
                out.append(name)
        except OSError:
            pass
    return out


def _delta_plan(source: Path, before: dict, excludes: list, ignored: list) -> dict:
    """What the worktree holds that `checkout` of HEAD does not give back: changed/untracked files,
    paths deleted from the worktree and empty untracked directories. A superset is harmless; the
    capture-time replay proves the plan complete or the caller falls back to a full tree."""
    skip = [*excludes, *ignored]
    files, deleted = set(), set()
    for xy, name, orig in _status_entries(source):
        if any(name == c or name.startswith(c + '/') for c in skip):
            continue
        if orig is not None and not os.path.lexists(source / orig):
            deleted.add(orig)
        if os.path.lexists(source / name):
            if not (source / name).is_dir() or (source / name).is_symlink():
                files.add(name)
        else:
            deleted.add(name)
    r = _run(['git', '-C', str(source), 'ls-files', '-z'], capture_output=True)
    if r.returncode:
        raise WorkspaceError('checkpoint: cannot list tracked files')
    tracked_dirs = set()
    for item in r.stdout.split(b'\0'):
        parts = Path(item.decode('utf-8', 'surrogateescape')).parts
        tracked_dirs.update('/'.join(parts[:i]) for i in range(1, len(parts) + 1))   # a gitlink is a dir too
    tree = before['tree']
    dirs = sorted(n for n, v in tree.items() if v[0] == 'dir' and n not in tracked_dirs
                  and not any(k.startswith(n + '/') for k in tree))
    return {'files': sorted(files), 'deleted': sorted(deleted), 'dirs': dirs}


def _delta_keep(full: dict, delta: dict) -> dict:
    """The part of the full inventory a delta tree holds: its files, their parent directories, its empty dirs."""
    keep = set(delta['files']) | set(delta['dirs'])
    for name in list(keep):
        parts = Path(name).parts
        keep.update('/'.join(parts[:i]) for i in range(1, len(parts)))
    return {k: v for k, v in full.items() if k in keep}


def _objects_dir(repo: Path) -> Path:
    objects = Path(git(repo, 'rev-parse', '--git-path', 'objects'))
    return objects if objects.is_absolute() else repo / objects


class CheckpointBaseMissing(WorkspaceError):
    """The base commit a snapshot (or its compacted form) needs is absent from the durable object store.
    Retrying cannot help: the snapshot stays restorable only where the base still is."""


def base_objects_dir(repo: Path, env: dict | None = None) -> Path | None:
    """Object directory of a repository (a worktree resolves to its common one); None when unreadable."""
    try:
        objects = Path(git(repo, 'rev-parse', '--git-path', 'objects', env=env))
    except (WorkspaceError, OSError):
        return None
    return objects if objects.is_absolute() else Path(repo) / objects


def _durable_objects(data: dict, fallback: Path | None = None) -> Path | None:
    """Where a snapshot's bundle base lives: the object store recorded at capture, else the caller's
    (a pool passes its base clone's), else the capture source's if it still exists."""
    for candidate in (data.get('objects'), fallback):
        if candidate and Path(candidate).is_dir():
            return Path(candidate)
    source = Path(data['source'])
    found = base_objects_dir(source) if source.is_dir() else None
    return found if found is not None and found.is_dir() else None


def _has_commit(repo: Path, sha: str) -> bool:
    return _run(['git', '-C', str(repo), 'cat-file', '-e', f'{sha}^{{commit}}'],
                          capture_output=True).returncode == 0


def _alternate(gitdir_objects: Path, reference: Path) -> None:
    info = gitdir_objects / 'info'
    info.mkdir(parents=True, exist_ok=True)
    (info / 'alternates').write_text(str(reference) + '\n')



class Checkpoints:
    def __init__(self, root: Path, reserve_bytes: int = 512 * 1024 * 1024, *, capture_min_free_bytes: int = 0,
                 exclude_names: tuple = DEFAULT_EXCLUDE_NAMES, slim: bool = True,
                 max_untracked_bytes: int = MAX_UNTRACKED_BYTES):
        self.root = root
        self.slim = slim
        self.max_untracked_bytes = max_untracked_bytes
        self.exclude_names = tuple(exclude_names)
        self.reserve_bytes = reserve_bytes
        self.capture_min_free_bytes = capture_min_free_bytes
        root.mkdir(parents=True, exist_ok=True, mode=0o700)
        root.chmod(0o700)

    def _budget(self, target: Path, needed: int, min_free_bytes: int = 0) -> None:
        try:
            free = shutil.disk_usage(target).free
        except OSError:
            raise WorkspaceError('checkpoint: disk availability unknown; lease retained') from None
        if free < needed + max(self.reserve_bytes, min_free_bytes):
            raise WorkspaceError('checkpoint: insufficient disk budget; lease retained')

    def create(self, key: str, source: Path, metadata: dict) -> Path:
        with _IO_LOCK:
            return self._create_best(key, source, metadata)

    def _create_best(self, key: str, source: Path, metadata: dict) -> Path:
        if not self.slim:
            return self._create(key, source, metadata, slim=False)
        try:
            return self._create(key, source, metadata, slim=True)
        except WorkspaceError as e:
            if 'insufficient disk' in str(e) or 'source changed' in str(e) or 'unsupported' in str(e):
                raise
            # The compact form did not replay to the same state (filters, skip-worktree, a
            # missing base): keep the full form, which is always self-contained.
            return self._create(key, source, metadata, slim=False, slim_failed=True)

    def _create(self, key: str, source: Path, metadata: dict, slim: bool = False, slim_failed: bool = False) -> Path:
        if not key or any(c not in 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_' for c in key):
            raise WorkspaceError('checkpoint: invalid key')
        final = self.root / key
        if final.exists():
            self.verify(final)
            return final
        plan = submodule_plan(source)
        if git(source, 'rev-parse', '--shared-index-path'):
            raise WorkspaceError('checkpoint: split index unsupported')
        excludes = find_excludes(source, self.exclude_names)
        ignored = []
        if slim:
            ignored = find_ignored(source, excludes)
            excludes += find_large_untracked(source, [*excludes, *ignored], self.max_untracked_bytes)
        before = fingerprint(source, plan, tuple(excludes), tuple(ignored))
        delta = _delta_plan(source, before, excludes, ignored) if slim and not plan else None
        if submodule_plan(source) != plan:
            raise WorkspaceError('checkpoint: source changed during capture; lease retained')
        modules = _modules_dir(source)
        size = sum(v[2] for v in before['tree'].values() if v[0] == 'file')
        stored = sum(before['tree'][n][2] for n in delta['files'] if before['tree'][n][0] == 'file') if delta else size
        # Full history bundle can be larger than the worktree; count the shared object store.
        objects = Path(git(source, 'rev-parse', '--git-path', 'objects'))
        if not objects.is_absolute():
            objects = source / objects
        object_size = sum(p.stat().st_size for p in objects.rglob('*') if p.is_file())
        object_size += sum(p.stat().st_size for e in plan if e['gitdir']
                           for p in (modules / e['name']).rglob('*') if p.is_file() and not p.is_symlink())
        # Snapshot plus scratch replay: two trees, the saved bundle and the
        # replay's object store. Budget one new capture, not every waiting slot.
        self._budget(self.root, size + stored + 3 * object_size, self.capture_min_free_bytes)
        pending = Path(tempfile.mkdtemp(prefix='.pending-', dir=self.root))
        pending.chmod(0o700)
        try:
            if delta is not None:
                self._copy_delta(source, pending / 'tree', before['tree'], delta)
            else:
                _copy(source, pending / 'tree', frozenset((*excludes, *ignored)))
            index = Path(git(source, 'rev-parse', '--git-path', 'index'))
            if not index.is_absolute():
                index = source / index
            shutil.copy2(index, pending / 'index')
            # HEAD alone omits blobs referenced only by the staged index. A stash
            # commit records them without changing HEAD/index/worktree; keep its ref.
            stash = _stash_create(source)
            refs = ['HEAD']
            base_sha = metadata.get('base_sha')
            ref = None
            if base_sha:
                base_ref = f'refs/runner-checkpoint-bases/{key}'
                git(source, 'update-ref', base_ref, base_sha)
                refs.append(base_ref)
            if stash:
                ref = f'refs/runner-checkpoints/{key}'
                git(source, 'update-ref', ref, stash)
                refs.append(ref)
            bundle = self._bundle(source, pending, refs, base_sha if slim else None, stash and ref)
            (pending / 'index').chmod(0o600)
            for i, entry in enumerate(plan):
                if entry['gitdir']:
                    self._capture_submodule(key, source, modules, entry, pending / 'submodules' / str(i))
            branch = git(source, 'symbolic-ref', '--quiet', 'HEAD', check=False) or None
            # `objects` outlives the source when that is a pool slot: a slot shares its base clone's store.
            # `excludes` is written even when empty: its absence marks the oldest format.
            manifest = {'version': 2 if plan else 1, 'source': str(source), 'metadata': metadata, 'branch': branch,
                        'base_sha': metadata.get('base_sha', before['head']), 'fingerprint': before,
                        'bytes': size, 'object_bytes': object_size, 'objects': str(objects),
                        'excludes': excludes}
            if ignored:
                manifest['ignored'] = ignored
            if slim_failed:
                manifest['slim_failed'] = True      # full form kept on purpose: not a migration candidate
            if delta is not None:
                manifest['delta'] = delta
                manifest['stored_bytes'] = stored
            if bundle:
                manifest['bundle'] = bundle
            if plan:
                manifest['submodules'] = plan
            atomic_json(pending / 'manifest.json', manifest)
            # Other writers can consume space during copying. Recheck before
            # scratch allocation; failure removes only this pending copy.
            self._budget(self.root, size + 2 * object_size, self.capture_min_free_bytes)
            self.verify(pending)
            if submodule_plan(source) != plan or fingerprint(source, plan, tuple(excludes), tuple(ignored)) != before:
                raise WorkspaceError('checkpoint: source changed during capture; lease retained')
            # fsync all regular files before publishing the checkpoint directory.
            for p in pending.rglob('*'):
                if p.is_file() and not p.is_symlink():
                    _sync(p)
            for p in sorted((p for p in pending.rglob('*') if p.is_dir() and not p.is_symlink()), reverse=True):
                _sync(p)
            _sync(pending)
            os.rename(pending, final)
            _sync(self.root)
            return final
        except Exception:
            # A partial capture has no authority; source is untouched. Do not accumulate
            # full-tree temporary copies on every poll after a verification failure.
            shutil.rmtree(pending, ignore_errors=True)
            raise

    def _bundle(self, source: Path, pending: Path, refs: list, base_sha: str | None, stash_ref: str | None):
        """Write commits.bundle. Slim form: only what `base_sha` (pinned by a checkpoint ref) lacks, with
        base_sha as the bundle's prerequisite; None when the full-history form was written."""
        out = pending / 'commits.bundle'
        known = base_sha and _run(['git', '-C', str(source), 'cat-file', '-e', f'{base_sha}^{{commit}}'],
                                            capture_output=True).returncode == 0
        if not known:
            git(source, 'bundle', 'create', str(out), *refs)
            out.chmod(0o600)
            return None
        has_head = bool(git(source, 'rev-list', '-n1', 'HEAD', f'^{base_sha}'))
        positive = (['HEAD'] if has_head else []) + ([stash_ref] if stash_ref else [])
        info = {'mode': 'incremental' if positive else 'none', 'base': base_sha, 'has_head': has_head}
        if positive:
            git(source, 'bundle', 'create', str(out), *positive, f'^{base_sha}')
            out.chmod(0o600)
        return info

    def _copy_delta(self, source: Path, dst: Path, full: dict, delta: dict) -> None:
        """Copy only the delta files (APFS clones where possible), parents with their recorded modes."""
        dst.mkdir()
        dirs = set(delta['dirs'])
        for name in delta['files']:
            src, out = source / name, dst / name
            dirs.update('/'.join(Path(name).parts[:i]) for i in range(1, len(Path(name).parts)))
            out.parent.mkdir(parents=True, exist_ok=True)
            if src.is_symlink():
                os.symlink(os.readlink(src), out)
            elif sys.platform == 'darwin' and _run(['cp', '-cp', str(src), str(out)],
                                                             capture_output=True).returncode == 0:
                continue
            else:
                shutil.copy2(src, out)
        for name in sorted(dirs, key=lambda n: -len(Path(n).parts)):
            (dst / name).mkdir(parents=True, exist_ok=True)
            if name in full:
                (dst / name).chmod(full[name][1])

    def _capture_submodule(self, key: str, source: Path, modules: Path, entry: dict, dest: Path) -> None:
        """Own bundle + index of one submodule gitdir. The source gitdir is only given a ref."""
        gd = modules / entry['name']
        dest.mkdir(parents=True, mode=0o700)
        refs = ['HEAD', '--branches', '--tags', '--remotes']
        if entry['populated']:
            # Blobs referenced only by the submodule's staged index.
            stash = _stash_create(source / entry['path'])
            if stash:
                ref = f'refs/runner-checkpoints/{key}'
                _gitdir(gd, 'update-ref', ref, stash)
                refs.append(ref)
        _gitdir(gd, 'bundle', 'create', str(dest / 'commits.bundle'), *refs)
        (dest / 'commits.bundle').chmod(0o600)
        if (gd / 'index').is_file():
            shutil.copy2(gd / 'index', dest / 'index')
            (dest / 'index').chmod(0o600)

    def read(self, checkpoint: Path) -> dict:
        with _IO_LOCK:      # a compaction holds this lock across its two renames
            retired = checkpoint.parent / f'.retired-{checkpoint.name}'
            if not os.path.lexists(checkpoint) and retired.is_dir():
                os.rename(retired, checkpoint)       # crash between the swap's two renames
        try:
            data = json.loads((checkpoint / 'manifest.json').read_text())
            if data['version'] not in (1, 2):
                raise ValueError()
            for entry in data.get('submodules', []):
                if not (_safe_rel(entry['path']) and _safe_rel(entry['name'])
                        and isinstance(entry['populated'], bool) and isinstance(entry['gitdir'], bool)):
                    raise ValueError()
            # No names supplied by a manifest may escape the tree.
            for name in [*data['fingerprint']['tree'], *data.get('excludes', [])]:
                p = Path(name)
                if not isinstance(name, str) or p.is_absolute() or '..' in p.parts or '.git' in p.parts:
                    raise ValueError()
            if not isinstance(data.get('excludes', []), list) or not isinstance(data.get('objects', ''), str):
                raise ValueError()
            return data
        except (OSError, ValueError, KeyError, TypeError):
            raise WorkspaceError('checkpoint: invalid manifest') from None

    def _prove_bundle(self, bundle: Path, refspecs: list, message: str, reference: Path | None = None) -> None:
        """`bundle verify` checks only the header; unpack into scratch storage to prove the pack."""
        with tempfile.TemporaryDirectory(prefix='.preflight-', dir=self.root) as scratch:
            probe = Path(scratch) / 'probe'
            ok = _run(['git', 'init', '--bare', '--quiet', str(probe)], capture_output=True).returncode == 0
            if ok and reference is not None:
                _alternate(probe / 'objects', reference)      # the bundle's prerequisite lives there
            ok = ok and _run(
                ['git', '--git-dir', str(probe), '-c', 'transfer.fsckObjects=true', 'fetch', '--quiet',
                 str(bundle), *refspecs], capture_output=True).returncode == 0
            if not ok:
                raise WorkspaceError('checkpoint: ' + message)

    def _replay(self, checkpoint: Path, target: Path, prove: bool = True) -> None:
        data = self.read(checkpoint)
        # Validate stored tree before touching the destination (no link-following extraction).
        subs = data.get('submodules', [])
        excludes = tuple(data.get('excludes', []))
        ignored = tuple(data.get('ignored', []))
        delta = data.get('delta')
        expected = _delta_keep(data['fingerprint']['tree'], delta) if delta else data['fingerprint']['tree']
        if inventory(checkpoint / 'tree', tuple(e['path'] for e in subs if e['populated'])) != expected:
            raise WorkspaceError('checkpoint: snapshot hash mismatch')
        modules = _modules_dir(target)
        stale = self._check_target_submodules(checkpoint, target, data)
        # Parent target: no active writer. A retry after a partial replay must still be able to overwrite.
        gitdir = Path(git(target, 'rev-parse', '--absolute-git-dir'))
        if any(os.path.lexists(gitdir / lock) for lock in ('index.lock', 'HEAD.lock')):
            raise WorkspaceError('checkpoint: active git writer in target; lease retained')
        # Preflight every stored component before the target is touched.
        for i, entry in enumerate(subs):
            if not entry['gitdir']:
                continue
            part = checkpoint / 'submodules' / str(i)
            if not (part / 'commits.bundle').is_file() or (entry['populated'] and not (part / 'index').is_file()):
                raise WorkspaceError('checkpoint: submodule snapshot incomplete')
            self._prove_bundle(part / 'commits.bundle', ['+refs/heads/*:refs/heads/*', '+refs/tags/*:refs/tags/*',
                                                         '+refs/remotes/*:refs/remotes/*', '+HEAD:refs/runner-replay/HEAD'],
                               'submodule bundle invalid; target untouched')
        bundle = data.get('bundle')
        if bundle:
            self._ensure_base(checkpoint, target, bundle['base'], data['source'])
        refspecs = ['+refs/*:refs/runner-replay/*', *(['HEAD'] if not bundle or bundle['has_head'] else [])]
        if bundle and bundle['mode'] == 'none':
            if _run(['git', '-C', str(target), 'cat-file', '-e', f"{data['fingerprint']['head']}^{{commit}}"],
                              capture_output=True).returncode:
                raise WorkspaceError('checkpoint: base commit missing in target; target untouched')
        elif prove:
            self._prove_bundle(checkpoint / 'commits.bundle', refspecs, 'bundle invalid; target untouched',
                               reference=_objects_dir(target) if bundle else None)
        self._set_aside_stale_submodules(target, stale)
        # Replay never needs the target's own submodules; a set-aside gitdir would break the recursion.
        if not (bundle and bundle['mode'] == 'none'):
            git(target, 'fetch', '--quiet', '--no-recurse-submodules', str(checkpoint / 'commits.bundle'), *refspecs)
        branch = data.get('branch')
        if isinstance(branch, str) and branch.startswith('refs/heads/'):
            git(target, 'checkout', '--quiet', '--force', '-B', branch[len('refs/heads/'):], data['fingerprint']['head'])
        else:
            git(target, 'checkout', '--quiet', '--force', '--detach', data['fingerprint']['head'])
        _clear_tree(target)
        if delta:
            self._overlay_delta(checkpoint / 'tree', target, data['fingerprint']['tree'], delta)
        else:
            for child in (checkpoint / 'tree').iterdir():
                dest = target / child.name
                if child.is_symlink():
                    os.symlink(os.readlink(child), dest)
                elif child.is_dir():
                    _copy(child, dest)
                else:
                    shutil.copy2(child, dest)
        index = Path(git(target, 'rev-parse', '--git-path', 'index'))
        if not index.is_absolute():
            index = target / index
        # A crash during copy must never leave a truncated authoritative index;
        # git itself uses atomic lock/rename for subsequent stat refreshes.
        index_tmp = index.with_name('runner-checkpoint-index.tmp')
        shutil.copy2(checkpoint / 'index', index_tmp)
        _sync(index_tmp)
        os.replace(index_tmp, index)
        _sync(index.parent)
        for i, entry in enumerate(subs):
            if entry['gitdir']:
                self._replay_submodule(checkpoint / 'submodules' / str(i), target, modules, entry, data)
        git(target, 'update-index', '--really-refresh', check=False)
        for entry in subs:
            if entry['populated']:
                git(target / entry['path'], 'update-index', '--really-refresh', check=False)
        if fingerprint(target, subs, excludes, ignored) != data['fingerprint']:
            raise WorkspaceError('checkpoint: replay verification failed; lease retained')

    @staticmethod
    def _ensure_base(checkpoint: Path, target: Path, base: str, source: str) -> None:
        """A slim bundle needs its base commit in the target. Pool slots share the base clone's objects;
        any other target gets it from the capture source, where a checkpoint ref pins it."""
        def have():
            return _run(['git', '-C', str(target), 'cat-file', '-e', f'{base}^{{commit}}'],
                                  capture_output=True).returncode == 0
        if have():
            return
        ref = f'refs/runner-checkpoint-bases/{checkpoint.name}'
        _run(['git', '-C', str(target), 'fetch', '--quiet', '--no-recurse-submodules', source, ref],
                       capture_output=True)       # objects only: no ref is written into the target
        if not have():
            raise WorkspaceError('checkpoint: base commit missing in target; target untouched')

    @staticmethod
    def _overlay_delta(tree: Path, target: Path, full: dict, delta: dict) -> None:
        """HEAD's files from the object store (already fetched), then the delta over them."""
        git(target, 'checkout-index', '--all', '--force')
        for name in delta['deleted']:
            p = target / name
            if os.path.lexists(p) and not p.is_dir():
                p.unlink()
        for name in sorted(delta['files']):
            src, out = tree / name, target / name
            out.parent.mkdir(parents=True, exist_ok=True)
            if os.path.lexists(out):
                if out.is_dir() and not out.is_symlink():
                    shutil.rmtree(out)
                else:
                    out.unlink()
            if src.is_symlink():
                os.symlink(os.readlink(src), out)
            else:
                shutil.copy2(src, out)
        for name in delta['dirs']:
            (target / name).mkdir(parents=True, exist_ok=True)
        # Checkout creates files with this process's umask; the source had its own. Put the recorded
        # modes back (files first, directories deepest-first so a read-only parent is closed last).
        for kind in ('file', 'link', 'dir'):
            for name in sorted((n for n, v in full.items() if v[0] == kind), key=lambda n: (-len(Path(n).parts), n)):
                p = target / name
                if not os.path.lexists(p) or stat.S_IMODE(p.lstat().st_mode) == full[name][1]:
                    continue
                try:
                    os.chmod(p, full[name][1], follow_symlinks=False)
                except NotImplementedError:     # no lchmod on this platform: a link's mode is not enforced there
                    pass

    def _check_target_submodules(self, checkpoint: Path, target: Path, data: dict) -> list:
        """Validate the submodule gitdirs already present in the target.

        A gitdir equal to the checkpointed one is kept (and must hold the same work). One that
        differs is a leftover of an earlier lease of this pooled slot: it is returned for
        `_set_aside_stale_submodules` when it provably holds nothing the remote lacks, otherwise
        the restore is refused. Nothing is changed here."""
        modules = _modules_dir(target)
        stale = []
        for entry in data.get('submodules', []):
            gd = modules / entry['name']
            if os.path.lexists(gd):
                if any(c.is_symlink() for c in (modules, *[gd.parents[k] for k in range(len(Path(entry['name']).parts) - 1)], gd)):
                    raise WorkspaceError('checkpoint: symlinked submodule gitdir in target unsupported')
                have = _submodule_state(target, {**entry, 'populated': False}, modules)
                want = data['fingerprint']['submodules'][entry['path']]
                if any(have.get(k) != want.get(k) for k in ('gitdir', 'head', 'branch', 'refs')):
                    if any(os.path.lexists(gd / lock) for lock in ('index.lock', 'HEAD.lock')):
                        raise WorkspaceError('checkpoint: active git writer in target submodule; lease retained')
                    why = _stale_submodule_work(target, entry, gd)
                    if why:
                        raise WorkspaceError(f'checkpoint: submodule gitdir differs in target ({why}); lease retained')
                    stale.append(entry)
                    continue
                if any(os.path.lexists(gd / lock) for lock in ('index.lock', 'HEAD.lock')):
                    raise WorkspaceError('checkpoint: active git writer in target submodule; lease retained')
                self._require_same_submodule_work(checkpoint, target, entry, data, gd)
        return stale

    def _set_aside_stale_submodules(self, target: Path, stale: list) -> None:
        """Move each stale gitdir and its worktree next to (not inside) the modules directory.

        The worktree goes whole, so tracked, untracked and ignored files all survive; replay
        then clears and fills an empty path. Both moves are renames; one that cannot be an
        atomic rename (another device) refuses the restore with the lease retained. The parked
        pair stays usable: the worktree `.git` pointer and the gitdir `core.worktree` are
        rewritten to the new locations (a standalone clone needs neither)."""
        modules = _modules_dir(target)
        todo = []
        for entry in stale:
            gd, wt = modules / entry['name'], target / entry['path']
            has_wt = wt.is_dir() and not wt.is_symlink() and any(wt.iterdir())
            if os.path.lexists(gd) or has_wt:       # else a crashed earlier replay already moved both
                todo.append((entry, gd, wt, has_wt))
        if not todo:
            return
        park = modules.parent / 'runner-stale-submodules'
        try:
            info = os.lstat(park)
        except FileNotFoundError:
            try:
                os.mkdir(park, 0o700)           # mkdir never follows a symlink at the last component
            except OSError as e:
                raise WorkspaceError(f'checkpoint: cannot create the set-aside directory ({e.strerror}); lease retained') from None
        else:
            if not stat.S_ISDIR(info.st_mode) or info.st_uid != os.getuid():
                raise WorkspaceError('checkpoint: set-aside path is a symlink, not a directory or not ours; lease retained')
        stamp = datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S')
        for entry, gd, wt, has_wt in todo:
            label = entry['name'].replace('/', '__')
            n = 0
            while True:
                dest = park / (f'{stamp}-{label}' + (f'-{n}' if n else ''))
                moved_wt = dest.with_name(dest.name + '.worktree')
                if not os.path.lexists(dest) and not os.path.lexists(moved_wt):
                    break
                n += 1
            try:
                if has_wt:
                    os.rename(wt, moved_wt)
                if os.path.lexists(gd):
                    os.rename(gd, dest)
            except OSError as e:
                if os.path.lexists(moved_wt) and not os.path.lexists(wt):
                    os.rename(moved_wt, wt)         # put the worktree back; nothing was lost
                raise WorkspaceError(f'checkpoint: cannot set aside stale submodule ({e.strerror}); lease retained') from None
            if has_wt and os.path.lexists(dest):
                self._reconnect_parked(dest, moved_wt)
            for parent in gd.parents:       # prune now-empty intermediate directories, never above modules
                if parent == modules.parent:
                    break
                try:
                    parent.rmdir()
                except OSError:
                    break
            _sync(park)

    @staticmethod
    def _reconnect_parked(gd: Path, wt: Path) -> None:
        """Best effort: point the parked worktree and gitdir at each other again."""
        pointer = wt / '.git'
        if pointer.is_file() and not pointer.is_symlink():
            tmp = pointer.with_name('.git.runner-tmp')
            tmp.write_text('gitdir: ' + os.path.relpath(os.path.realpath(gd), os.path.realpath(wt)) + '\n')
            os.replace(tmp, pointer)
        if _gitdir(gd, 'config', '--get', 'core.worktree', check=False):
            _gitdir(gd, 'config', 'core.worktree', os.path.relpath(os.path.realpath(wt), os.path.realpath(gd)), check=False)

    def _require_same_submodule_work(self, checkpoint: Path, target: Path, entry: dict, data: dict, gd: Path) -> None:
        """An existing target submodule may hold newer work; never replace anything that differs."""
        i = data['submodules'].index(entry)
        saved = checkpoint / 'submodules' / str(i) / 'index'
        have_index = (gd / 'index').read_bytes() if (gd / 'index').is_file() else None
        want_index = saved.read_bytes() if saved.is_file() else None
        wt = target / entry['path']
        present = wt.is_dir() and not wt.is_symlink() and any(wt.iterdir())
        # Stat refreshes rewrite index bytes; with a live worktree compare the staged content instead.
        differs = not present and have_index is not None and have_index != want_index
        if present:
            have = _submodule_state(target, entry, _modules_dir(target))
            want = data['fingerprint']['submodules'][entry['path']]
            differs = differs or have != want
            prefix = entry['path'] + '/'
            roots = tuple(e['path'] for e in data['submodules'] if e['populated'])
            now = {k: v for k, v in inventory(target, roots, frozenset(data.get('excludes', []))).items() if k.startswith(prefix)}
            differs = differs or now != {k: v for k, v in data['fingerprint']['tree'].items() if k.startswith(prefix)}
        if differs:
            raise WorkspaceError('checkpoint: submodule work in target differs from checkpoint; lease retained')

    def _replay_submodule(self, src: Path, target: Path, modules: Path, entry: dict, data: dict) -> None:
        gd = modules / entry['name']
        want = data['fingerprint']['submodules'][entry['path']]
        if not os.path.lexists(gd):
            gd.parent.mkdir(parents=True, exist_ok=True)
            _run(['git', 'init', '--bare', '--quiet', str(gd)], check=True, capture_output=True)
            _gitdir(gd, 'fetch', '--quiet', str(src / 'commits.bundle'),
                    '+refs/heads/*:refs/heads/*', '+refs/tags/*:refs/tags/*',
                    '+refs/remotes/*:refs/remotes/*', '+refs/runner-checkpoints/*:refs/runner-checkpoints/*',
                    '+HEAD:refs/runner-replay/HEAD')
            if want['branch']:
                _gitdir(gd, 'symbolic-ref', 'HEAD', want['branch'])
            else:
                _gitdir(gd, 'update-ref', '--no-deref', 'HEAD', want['head'])
            _gitdir(gd, 'update-ref', '-d', 'refs/runner-replay/HEAD')
            wt = target / entry['path']
            _gitdir(gd, 'config', 'core.bare', 'false')
            _gitdir(gd, 'config', 'core.worktree', os.path.relpath(os.path.realpath(wt), os.path.realpath(gd)))
        if any(os.path.lexists(gd / lock) for lock in ('index.lock', 'HEAD.lock')):
            raise WorkspaceError('checkpoint: active git writer in target submodule; lease retained')
        if (src / 'index').is_file():
            tmp = gd / 'runner-checkpoint-index.tmp'
            shutil.copy2(src / 'index', tmp)
            _sync(tmp)
            os.replace(tmp, gd / 'index')
            _sync(gd)
        if entry['populated']:
            pointer = target / entry['path'] / '.git'
            if pointer.is_symlink():
                raise WorkspaceError('checkpoint: unsafe submodule pointer')
            tmp = pointer.with_name('.git.runner-tmp')
            tmp.write_text('gitdir: ' + os.path.relpath(os.path.realpath(gd), os.path.realpath(pointer.parent)) + '\n')
            os.replace(tmp, pointer)

    def verify(self, checkpoint: Path) -> None:
        with _IO_LOCK:
            self._verify(checkpoint)

    def _verify(self, checkpoint: Path) -> None:
        data = self.read(checkpoint)
        self._budget(self.root, data['bytes'] + 2 * data['object_bytes'])
        with tempfile.TemporaryDirectory(prefix='.verify-', dir=self.root) as name:
            target = Path(name)
            git(target, 'init', '--quiet')
            if data.get('bundle'):
                objects = _durable_objects(data)
                if objects is None:
                    raise WorkspaceError('checkpoint: bundle base unavailable')
                _alternate(target / '.git' / 'objects', objects)
            self._replay(checkpoint, target, prove=False)

    def is_old_format(self, checkpoint: Path) -> bool:
        """True for a snapshot that predates the slim form (full tree, full bundle), or the cache-exclusion
        format and still holds some caches: `compact` rewrites it."""
        data = self.read(checkpoint)
        if 'delta' in data:
            return False        # slim form: caches are never in a delta tree
        if self.slim and not data.get('slim_failed') and not data.get('submodules'):
            return True
        if 'excludes' in data:
            return False
        return any(name in self.exclude_names for rel in data['fingerprint']['tree']
                   for name in Path(rel).parts)

    def compact(self, checkpoint: Path, base_objects: Path | None = None) -> dict:
        """Rewrite an old-format snapshot in place as a new-format one (same directory name).

        The old snapshot is replayed into scratch (hash-verified against its own fingerprint), a new
        snapshot is captured from that scratch and replay-verified, and only then the directory is
        swapped. Any failure leaves the old snapshot untouched. Returns {'compacted', 'before', 'after'}.

        The capture slot is usually gone by now. The base commit is taken from the object store the
        manifest records, else from `base_objects` (the pool's base clone, for a manifest written
        before `objects` was recorded); `CheckpointBaseMissing` when that store lacks it."""
        with _IO_LOCK:
            return self._compact(checkpoint, base_objects)

    def _compact(self, checkpoint: Path, base_objects: Path | None = None) -> dict:
        retired = self.root / f'.retired-{checkpoint.name}'
        if not self.is_old_format(checkpoint):
            return {'compacted': False}
        data = self.read(checkpoint)
        if data.get('submodules'):
            # Not supported: recapture of configured submodules. Reported, never silent.
            return {'compacted': False, 'skipped': 'submodules'}
        before = _du(checkpoint)
        key = f'compact-{uuid.uuid4().hex}'     # unique: never names an existing checkpoint
        created = self.root / key
        scratch = Path(tempfile.mkdtemp(prefix='.compact-src-', dir=self.root))
        try:
            self._budget(self.root, data['bytes'] + 3 * data['object_bytes'], self.capture_min_free_bytes)
            git(scratch, 'init', '--quiet')
            # The scratch borrows the durable store, as a pool slot does: a slim replay finds its base
            # there, and the new capture bundles only what the base lacks, so it verifies from there too.
            objects = _durable_objects(data, base_objects)
            base = (data.get('bundle') or {}).get('base') or data['metadata'].get('base_sha')
            if objects is not None:
                _alternate(scratch / '.git' / 'objects', objects)
            if base and objects is None:
                raise WorkspaceError('checkpoint: bundle base unavailable')
            if base and not _has_commit(scratch, base):
                raise CheckpointBaseMissing('checkpoint: bundle base missing from the base clone')
            self._replay(checkpoint, scratch, prove=True)
            self._create_best(key, scratch, data['metadata'])
            manifest = self.read(created)
            if (manifest['fingerprint']['head'] != data['fingerprint']['head']
                    or manifest['metadata'] != data['metadata'] or manifest.get('branch') != data.get('branch')):
                raise WorkspaceError('checkpoint: compacted snapshot differs in head/metadata/branch')
            manifest['source'] = data['source']
            if objects is not None:
                manifest['objects'] = str(objects)
            else:
                manifest.pop('objects', None)       # the scratch store is about to be deleted
            atomic_json(created / 'manifest.json', manifest)
            self._verify(created)
            os.rename(checkpoint, retired)
            try:
                os.rename(created, checkpoint)
            except BaseException:
                os.rename(retired, checkpoint)      # never leave the only copy under .retired-
                raise
            _sync(self.root)
            shutil.rmtree(retired, ignore_errors=True)
            return {'compacted': True, 'before': before, 'after': _du(checkpoint)}
        finally:
            shutil.rmtree(scratch, ignore_errors=True)
            shutil.rmtree(created, ignore_errors=True)

    @staticmethod
    def _marker(target: Path) -> Path:
        path = Path(git(target, 'rev-parse', '--git-path', 'runner-restore-marker.json'))
        return path if path.is_absolute() else target / path

    @staticmethod
    def _result_digest(data: dict) -> str:
        return hashlib.sha256(json.dumps(data['fingerprint'], sort_keys=True).encode()).hexdigest()

    def restore(self, checkpoint: Path, target: Path) -> dict:
        """Replay over target. A completed restore leaves a marker holding the digest of its
        result; a later restore of the same checkpoint refuses if target moved on since. No
        marker (crash mid-replay) means a partial replay, which a retry must overwrite."""
        with _IO_LOCK:
            data = self.read(checkpoint)
            marker = self._marker(target)
            try:
                done = json.loads(marker.read_text())
            except (OSError, ValueError):
                done = None
            if isinstance(done, dict) and done.get('checkpoint') == checkpoint.name:
                # Submodule-specific refusals first: the plain fingerprint cannot see inside a populated submodule.
                self._check_target_submodules(checkpoint, target, data)
                current = hashlib.sha256(json.dumps(
                    fingerprint(target, data.get('submodules'), tuple(data.get('excludes', [])),
                                tuple(data.get('ignored', []))), sort_keys=True).encode()).hexdigest()
                if current != done.get('result'):
                    raise WorkspaceError('checkpoint: target has newer work since completed restore; refused')
            self._budget(target, data['bytes'] + data['object_bytes'])
            # Drop the marker before touching target: an interrupted replay must stay retryable.
            marker.unlink(missing_ok=True)
            _sync(marker.parent)
            self._replay(checkpoint, target)
            atomic_json(marker, {'checkpoint': checkpoint.name, 'result': self._result_digest(data)})
            return data
